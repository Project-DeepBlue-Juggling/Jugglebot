# ── CRC-16/CCITT-FALSE ─────────────────────────────────────────────────
def crc16_ccitt(data: bytes) -> int:
    crc = 0xFFFF
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) & 0xFFFF if (crc & 0x8000) else (crc << 1) & 0xFFFF
    return crc & 0xFFFF

# ── Frame header ───────────────────────────────────────────────────────
_HEADER_FMT = "<HBBHH"  # magic, version, msg_type, seq, length
assert struct.calcsize(_HEADER_FMT) == HEADER_SIZE

def encode_frame(msg_type: int, seq: int, payload: bytes) -> bytes:
    """Build a full wire frame: header + payload + CRC-16."""
    if len(payload) > MAX_PAYLOAD:
        raise ValueError(f"payload {len(payload)} > MAX_PAYLOAD {MAX_PAYLOAD}")
    head = struct.pack(_HEADER_FMT, MAGIC, PROTOCOL_VERSION, msg_type,
                       seq & 0xFFFF, len(payload))
    body = head + payload
    crc = crc16_ccitt(body)
    return body + struct.pack('<H', crc)

def decode_frame(frame: bytes):
    """Validate + parse a wire frame. Returns (msg_type, seq, payload).

    Raises ValueError on bad magic/version/length/CRC.
    """
    if len(frame) < HEADER_SIZE + CRC_SIZE:
        raise ValueError("frame too short")
    magic, version, msg_type, seq, length = struct.unpack_from(_HEADER_FMT, frame, 0)
    if magic != MAGIC:
        raise ValueError(f"bad magic 0x{magic:04X}")
    if version != PROTOCOL_VERSION:
        raise ValueError(f"bad version {version}")
    if HEADER_SIZE + length + CRC_SIZE != len(frame):
        raise ValueError(f"length {length} inconsistent with frame {len(frame)}")
    want = crc16_ccitt(frame[:HEADER_SIZE + length])
    got = struct.unpack_from('<H', frame, HEADER_SIZE + length)[0]
    if want != got:
        raise ValueError(f"CRC mismatch want 0x{want:04X} got 0x{got:04X}")
    payload = frame[HEADER_SIZE:HEADER_SIZE + length]
    return msg_type, seq, payload

