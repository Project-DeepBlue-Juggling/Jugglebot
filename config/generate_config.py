def _is_2d_list(val) -> bool:
    """Check if val is a list of lists (2D array)."""
    return isinstance(val, list) and len(val) > 0 and isinstance(val[0], list)


def _cpp_type_and_val(val) -> tuple[str, str]:
    """Return (C++ type, formatted value) for a scalar."""
    if isinstance(val, bool):
        return "bool", "true" if val else "false"
    if isinstance(val, str):
        return "const char*", f'"{val}"'
    if isinstance(val, int):
        if val < 0:
            return "int32_t", str(val)
        return "uint32_t", f"{val}u"
    if isinstance(val, float):
        return "float", f"{val}f"
    return "auto", str(val)


def _py_val(val) -> str:
    """Return formatted Python value for a scalar or list."""
    if isinstance(val, bool):
        return "True" if val else "False"
    return repr(val)


def compute_derived(cfg: dict) -> dict:
    """Compute derived constants from raw hardware config values."""
    derived = {}

    g = cfg["physics"]["gravity_mps2"]
    derived["GRAVITY_MMPS2"] = g * 1000.0

    # Init leg lengths with ball joint offset added
    geom = cfg["jugglebot_geometry"]
    offset = geom["ball_joint_offset_mm"]
    derived["INIT_LEG_LENGTHS_WITH_OFFSET_MM"] = [
        ll + offset for ll in geom["init_leg_lengths_mm"]
    ]

    # Teensy linear gain: rev/m
    tt = cfg["teensy_trajectory"]
    derived["TEENSY_LINEAR_GAIN"] = tt["linear_gain_factor"] / (math.pi * tt["hand_spool_radius_m"] * 2.0)

    # Ball Butler linear gain: rev/m
    bt = cfg["ball_butler_trajectory"]
    derived["BB_LINEAR_GAIN"] = bt["linear_gain_factor"] / (math.pi * bt["hand_spool_radius_m"] * 2.0)

    # Ball Butler trajectory buffer sizing
    max_throw_samples = int(bt["max_throw_duration_s"] * bt["sample_rate_hz"]) + 1
    derived["BB_MAX_THROW_SAMPLES"] = max_throw_samples
    derived["BB_MAX_TRAJ_FRAMES"] = max_throw_samples + bt["max_smooth_samples"] + bt["max_pause_samples"]

    return derived


def generate_hw_python(cfg: dict) -> str:
    """Generate hardware_config.py from hardware_config.yaml."""
    lines = [
        '"""',
        "AUTO-GENERATED by generate_config.py — DO NOT EDIT",
        "Source: config/hardware_config.yaml",
        "",
        "Centralised hardware & geometry constants for the Jugglebot system.",
        "Consumed by: ROS2 Python nodes (motion planner, CAN node, mocap, etc.)",
        "To regenerate: python config/generate_config.py",
        '"""',
        "",
        "import math",
    ]

    for yaml_key, py_prefix, _, section_title in HW_SECTIONS:
        section = cfg.get(yaml_key, {})
        if not section:
            continue
        lines += py_section(section_title)
        for key, val in section.items():
            name = f"{py_prefix}{key.upper()}"
            if _is_2d_list(val):
                lines.append(f"{name} = [")
                for row in val:
                    lines.append(f"    {row},")
                lines.append("]")
            elif isinstance(val, list):
                lines.append(f"{name} = {val}")
            else:
                lines.append(f"{name} = {_py_val(val)}")

    # Derived constants
    derived = compute_derived(cfg)
    lines += py_section("Derived Constants (computed by generator)")
    lines.append(f"GRAVITY_MMPS2 = {derived['GRAVITY_MMPS2']}")
    lines.append(f"INIT_LEG_LENGTHS_WITH_OFFSET_MM = {derived['INIT_LEG_LENGTHS_WITH_OFFSET_MM']}")
    lines.append(f"TEENSY_LINEAR_GAIN = {derived['TEENSY_LINEAR_GAIN']}")
    lines.append(f"BB_LINEAR_GAIN = {derived['BB_LINEAR_GAIN']}")
    lines.append(f"BB_MAX_THROW_SAMPLES = {derived['BB_MAX_THROW_SAMPLES']}")
    lines.append(f"BB_MAX_TRAJ_FRAMES = {derived['BB_MAX_TRAJ_FRAMES']}")
    lines.append("")

    return "\n".join(lines)


def generate_hw_cpp(cfg: dict) -> str:
    """Generate hardware_config.h from hardware_config.yaml."""
    lines = [
        "#pragma once",
        "// AUTO-GENERATED by generate_config.py — DO NOT EDIT",
        "// Source: config/hardware_config.yaml",
        "//",
        "// Centralised hardware & geometry constants for the Jugglebot system.",
        "// Consumed by: Ball Butler firmware, Platform Teensy firmware, ROS2 (via Python).",
        "// To regenerate: python config/generate_config.py",
        "",
        "#include <cstdint>",
        "#include <cmath>",
        "",
        "#ifndef M_PI",
        "#define M_PI 3.14159265358979323846",
        "#endif",
    ]

    for yaml_key, _, cpp_ns, section_title in HW_SECTIONS:
        section = cfg.get(yaml_key, {})
        if not section:
            continue
        lines += cpp_section(section_title)
        lines.append(f"namespace {cpp_ns} {{")
        for key, val in section.items():
            cpp_name = key.upper()
            if _is_2d_list(val):
                rows = len(val)
                cols = len(val[0])
                lines.append(f"  constexpr float {cpp_name}[{rows}][{cols}] = {{")
                for row in val:
                    formatted = ", ".join(f"{v}f" for v in row)
                    lines.append(f"    {{{formatted}}},")
                lines.append("  };")
            elif isinstance(val, list):
                count = len(val)
                ctype, _ = _cpp_type_and_val(val[0])
                if ctype == "float":
                    formatted = ", ".join(f"{v}f" for v in val)
                else:
                    formatted = ", ".join(str(v) for v in val)
                lines.append(f"  constexpr {ctype} {cpp_name}[{count}] = {{{formatted}}};")
            else:
                ctype, cval = _cpp_type_and_val(val)
                lines.append(f"  constexpr {ctype} {cpp_name} = {cval};")
        lines.append("}")

    # NOTE: Derived constants (LINEAR_GAIN, MAX_THROW_SAMPLES, etc.) are intentionally
    # omitted from the C++ output. Both firmwares derive these locally from source
    # constants — see BallButlerConfig.h TrajCfg namespace and Trajectory.h.
    # Python derived constants are still generated in generate_hw_python().
    lines.append("")

    return "\n".join(lines)


# ── Main ────────────────────────────────────────────────────────────────────

def main():
    yaml_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_YAML
    if not yaml_path.exists():
        print(f"Error: YAML file not found: {yaml_path}", file=sys.stderr)
        sys.exit(1)

    cfg = load_yaml(yaml_path)
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    # ── Protocol config ──
    cpp_path = OUTPUT_DIR / "protocol_config.h"
    py_path = OUTPUT_DIR / "protocol_config.py"

    cpp_content = generate_cpp(cfg)
    py_content = generate_python(cfg)

    cpp_path.write_text(cpp_content, encoding="utf-8")
    py_path.write_text(py_content, encoding="utf-8")

    print(f"Generated: {cpp_path}")
    print(f"Generated: {py_path}")

    # Copy protocol files to consumer directories
    extra_copies = [
        (cpp_content, BB_FIRMWARE_DIR / "protocol_config.h"),
        (cpp_content, PLATFORM_FIRMWARE_DIR / "protocol_config.h"),
        (py_content, ROS_PKG_DIR / "protocol_config.py"),
    ]
    for content, dest in extra_copies:
        if dest.parent.exists():
            dest.write_text(content, encoding="utf-8")
            print(f"Copied:    {dest}")
        else:
            print(f"Skipped (dir not found): {dest}")

    # ── Hardware config ──
    if HW_YAML.exists():
        hw_cfg = load_yaml(HW_YAML)

        hw_cpp_path = OUTPUT_DIR / "hardware_config.h"
        hw_py_path = OUTPUT_DIR / "hardware_config.py"

        hw_cpp_content = generate_hw_cpp(hw_cfg)
        hw_py_content = generate_hw_python(hw_cfg)

        hw_cpp_path.write_text(hw_cpp_content, encoding="utf-8")
        hw_py_path.write_text(hw_py_content, encoding="utf-8")

        print(f"Generated: {hw_cpp_path}")
        print(f"Generated: {hw_py_path}")

        # Copy hardware config to consumer directories
        hw_copies = [
            (hw_cpp_content, BB_FIRMWARE_DIR / "hardware_config.h"),
            (hw_cpp_content, PLATFORM_FIRMWARE_DIR / "hardware_config.h"),
            (hw_py_content, ROS_PKG_DIR / "hardware_config.py"),
        ]
        for content, dest in hw_copies:
            if dest.parent.exists():
                dest.write_text(content, encoding="utf-8")
                print(f"Copied:    {dest}")
            else:
                print(f"Skipped (dir not found): {dest}")
    else:
        print(f"Skipped hardware config (not found): {HW_YAML}")


if __name__ == "__main__":
    main()
