"""Currency and field contract for the three plan boards.

``plans/{active,parked,archived}/INDEX.md`` are GENERATED by
``python -m mapkit gen`` from plan frontmatter. This file pins:

* currency -- each committed INDEX equals the in-memory regeneration, byte for byte;
* fields -- every plan carries the frontmatter its board's columns are built from;
* filesystem rules -- bare archived filenames (``DOCUMENTATION_GUIDE.md`` 2.6), one
  board per filename, no self-link;
* the steps-to-headings mirror rule for every plan that declares ``steps:``.

Pure text, no network, no fixed ports -- safe under xdist.
"""
from __future__ import annotations

import os
import re

import pytest

from mapkit.gen_index import render_all
from mapkit.plans import BOARDS, load_plans
from mapkit.steps import check_mirror

_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
_DATE_PREFIX_RE = re.compile(r'^\d{4}-\d{2}-\d{2}[ _-]')
_REQUIRED = {
    'active': ('status', 'scope', 'last_updated', 'pathway'),
    'parked': ('parked', 'parked_why', 'unpark', 'pathway'),
    'archived': ('archived',),
}
_GEN = 'python -m mapkit gen'


def _dir(board):
    return os.path.join(_REPO_ROOT, 'plans', board)


def _plan_files(board):
    return sorted(n for n in os.listdir(_dir(board)) if n.endswith('.md') and n != 'INDEX.md')


@pytest.mark.parametrize('board', BOARDS)
def test_index_file_exists(board):
    assert os.path.isfile(os.path.join(_dir(board), 'INDEX.md'))


@pytest.mark.parametrize('board', BOARDS)
def test_index_is_current(board):
    """The committed INDEX equals the regeneration from plan frontmatter."""
    expected = render_all(_REPO_ROOT)[board]
    with open(os.path.join(_dir(board), 'INDEX.md'), encoding='utf-8') as fh:
        actual = fh.read()
    assert actual == expected, 'plans/%s/INDEX.md is stale; run `%s` and commit the result' % (board, _GEN)


def test_every_plan_has_its_board_fields():
    """Each plan carries the frontmatter its board's columns come from (lists every offender)."""
    missing = []
    for plan in load_plans(_REPO_ROOT):
        required = _REQUIRED[plan.board]
        for key in required:
            if key == 'pathway' and plan.meta.get('kind') == 'reference':
                continue
            if not plan.meta.get(key):
                missing.append('%s/%s: missing %s' % (plan.board, plan.filename, key))
    assert not missing, 'plans missing board fields:\n' + '\n'.join(missing)


def test_archived_plan_filenames_are_bare():
    """A plan's filename never changes for its life; the date lives in ``archived:``."""
    prefixed = [n for n in _plan_files('archived') if _DATE_PREFIX_RE.match(n)]
    assert not prefixed, (
        'archived plans carry a date prefix: %s. git mv them back to the bare name and record '
        'the date in `archived:` (DOCUMENTATION_GUIDE.md 2.6).' % prefixed)


def test_no_plan_filename_is_claimed_by_two_boards():
    seen = {}
    for board in BOARDS:
        for name in _plan_files(board):
            seen.setdefault(name, []).append(board)
    dup = {n: b for n, b in seen.items() if len(b) > 1}
    assert not dup, 'filenames on more than one board: %s' % dup


@pytest.mark.parametrize('board', BOARDS)
def test_index_does_not_list_itself(board):
    with open(os.path.join(_dir(board), 'INDEX.md'), encoding='utf-8') as fh:
        assert '](INDEX.md)' not in fh.read()


def test_plans_with_steps_pass_the_mirror_rule():
    offenders = []
    for plan in load_plans(_REPO_ROOT):
        offenders.extend(check_mirror(plan))
    assert not offenders, 'steps/heading mirror offenders:\n' + '\n'.join(offenders)
