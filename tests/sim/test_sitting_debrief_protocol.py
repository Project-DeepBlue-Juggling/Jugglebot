"""The `/sitting-debrief` command file keeps every promise the Runbook's close-out makes.

`docs/runbook.md` (generated by `mapkit.sitting.render_runbook`) ends with a `## Close-out`
that sends the owner to `/sitting-debrief <date>`. This test pins that the command file still
names each step that close-out and `plans/active/night-shift.md` § 4 P5 promise, so a later
edit of the protocol cannot silently drop one (per-Item merges, never the candidate branch;
the single-writer check; no force-push; the rebuild; `docs/records.md`; the follow-ups; the
logbook entry; `mapkit gen`). It also pins that the Night Shift protocol lists unaddressed
Sitting results, the one step P5 adds to it.
"""
from __future__ import annotations

import os
import re

import pytest

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEBRIEF = os.path.join(REPO, ".claude", "commands", "sitting-debrief.md")
NIGHT_SHIFT = os.path.join(REPO, ".claude", "commands", "night-shift.md")


def _read(path: str) -> str:
    with open(path, encoding="utf-8") as fh:
        return fh.read()


@pytest.fixture(scope="module")
def debrief() -> str:
    return _read(DEBRIEF)


PROMISES = {
    "reads the Sitting results": r"## Sitting result \(<date>\)",
    "merges per Item, never the candidate branch": r"never merge the candidate branch",
    "merges each held branch by name": r"night-shift/<d>-<ID>",
    "closes a passed Item with the Sitting as evidence": r"set-status <ID> complete",
    "keeps a failed Item in progress": r"set-status <ID> in_progress",
    "returns the live checkout to main": r"git checkout main",
    "rebuilds when ros_ws changed": r"colcon build --packages-select\s+jugglebot",
    "commits docs/records.md": r"docs/records\.md",
    "files follow-ups from the notes": r"python -m mapkit item new <bug\|feature\|idea>",
    "writes the logbook entry": r"logbook/<date>-sitting-debrief\.md",
    "regenerates the Runbook": r"python -m mapkit gen",
    "runs the suite gate before the commit": r"\./run_tests\.sh",
    "carries the Logbook-Entry trailer": r"Logbook-Entry: <date>-sitting-debrief",
    "checks for a peer Session first": r"git fetch && git status -sb",
    "forbids a force-push": r"never a force-push",
    "forbids stash and branch -f": r"Never `git stash`, never `git branch -f`",
    "aborts a conflicting merge": r"git( -C \S+)? merge --abort",
    "has a dry run": r"--dry-run",
    "re-runs the gate waiving only the hardware condition": r"night_shift_gate\.py[^`]*--waive c",
    "looks for a held branch before the plain-check path": r"git branch -r --list 'origin/night-shift/\*-<ID>'",
    "brings the branch up to date before gating it": r"merge --no-edit \$BASE",
    "keeps the base across tool calls": r"git rev-parse main > temp/reports/debrief/base-<ID>",
    "refuses to audit an empty diff": r"an audit of an empty diff finds nothing",
    "names the commit when taking main's copy": r"checkout \$BASE -- <paths>",
    "starts section 3 on main": r"Be on `main` first",
    "keeps the flown branch as it is on the remote": r"stays as it is on the remote",
    "names the only conflicts with a mechanical answer": r"These three,\s+and no others",
    "audits the updated tip": r"audit-reporter",
    "runs the full suite with no network": r"night_shift_nonet\.sh \./run_tests\.sh --full",
    "runs the gate from an extract of the base": r"git archive \$BASE tools/night_shift_gate\.py mapkit",
    "gates against the base it updated to": r"--base \$BASE",
    "keeps the suite from outlasting its call": r"run_in_background",
    "merges only the gated tip": r"merge -q --ff-only night-shift/<d>-<ID>",
    "leaves no local copy behind": r"git worktree remove --force temp/debrief-<ID>",
}


@pytest.mark.parametrize("promise", sorted(PROMISES))
def test_debrief_names_every_close_out_step(debrief, promise):
    assert re.search(PROMISES[promise], debrief), "sitting-debrief.md no longer %s" % promise


def test_debrief_frontmatter_has_description(debrief):
    head = debrief.split("---", 2)
    assert len(head) >= 3 and "description:" in head[1]
    assert "/sitting-debrief [<date>]" in head[1]


def test_debrief_has_analysis_phase_before_paperwork(debrief):
    i = debrief.index("## 1. Analyse the data")
    assert i < debrief.index("## 2. Read the results")
    for needle in ("AskUserQuestion", "goal dispatched", "ENDED (", "Runbook verdicts",
                   "attempt-killer", "Crosswalk", "verdict table", "sitting-wrapup.md"):
        assert needle in debrief, needle


def test_debrief_uses_glossary_words(debrief):
    # Sitting is robot time; a Session is a conversation. "runsheet" is an Avoid word.
    assert "runsheet" not in debrief.lower()
    assert re.search(r"\bSitting\b", debrief)


def test_night_shift_protocol_lists_unaddressed_sitting_results():
    text = _read(NIGHT_SHIFT)
    assert "## Unaddressed Sitting results" in text or "Unaddressed Sitting results" in text
    assert "## Sitting result (<date>)" in text


def test_runbook_close_out_points_at_debrief():
    from mapkit.sitting import render_runbook  # P4 lands this module

    page = render_runbook(REPO)
    assert "## Close-out" in page
    assert "/sitting-debrief <date>" in page
