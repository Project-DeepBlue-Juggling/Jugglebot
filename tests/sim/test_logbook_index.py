"""Currency and generator contract for ``logbook/INDEX.md``.

``logbook/INDEX.md`` is GENERATED by ``python -m mapkit gen`` from entry
frontmatter (``mapkit/gen_logbook.py``), as the three plan boards are
(``tests/sim/test_plans_index.py``). This file pins:

* currency -- the committed INDEX equals the in-memory regeneration, byte for byte,
  so a hand-added row, a missing row or a stale title fails here;
* the generator on a ``tmp_path`` logbook: order, title cap, ``|`` escaping, the
  fallbacks for irregular historical entries, structural files skipped, idempotence.

Pure text, no network, no fixed ports -- safe under xdist.
"""
from __future__ import annotations

import os

from mapkit.__main__ import main
from mapkit.gen_logbook import (
    ELLIPSIS, STRUCTURAL, TITLE_CAP, cap_title, entry_files, fallback_counts, load_entries,
    render, write_index,
)

_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
_INDEX = os.path.join(_REPO_ROOT, 'logbook', 'INDEX.md')
_GEN = 'python -m mapkit gen'


def test_index_is_current():
    """The committed INDEX equals the regeneration from entry frontmatter."""
    expected = render(load_entries(_REPO_ROOT))
    with open(_INDEX, encoding='utf-8') as fh:
        actual = fh.read()
    assert actual == expected, (
        'logbook/INDEX.md is stale (a row was hand-edited, or an entry was added or changed '
        'without regenerating); run `%s` and commit logbook/INDEX.md' % _GEN)


def test_every_entry_has_exactly_one_row():
    with open(_INDEX, encoding='utf-8') as fh:
        text = fh.read()
    for name in entry_files(_REPO_ROOT):
        assert text.count('](%s)' % name) == 1, name


# --- the generator on a tmp_path logbook --------------------------------------
def _entry(root, name, text):
    d = root / 'logbook'
    d.mkdir(exist_ok=True)
    (d / name).write_text(text, encoding='utf-8')


def _fm(title, date, status='resolved', phase='p'):
    return ('---\ntitle: "%s"\ntype: bugfix\ndate: %s\nstatus: %s\n%s---\n# H\n'
            % (title, date, status, ('phase: %s\n' % phase) if phase else ''))


def _rows(text):
    return [l for l in text.splitlines() if l.startswith('| 2')]


def _logbook(tmp_path):
    _entry(tmp_path, '2026-01-01-old.md', _fm('Old', '2026-01-01'))
    _entry(tmp_path, '2026-03-01-a.md', _fm('Same day A', '2026-03-01'))
    _entry(tmp_path, '2026-03-01-b.md', _fm('Same day B', '2026-03-01'))
    _entry(tmp_path, '2026-02-01-pipe.md', _fm('ROS | UDP panel', '2026-02-01', phase=None))
    for name in STRUCTURAL:
        _entry(tmp_path, name, '# structural\n')
    (tmp_path / 'logbook' / 'artifacts').mkdir()
    (tmp_path / 'logbook' / 'artifacts' / '2026-04-01-nested.md').write_text(_fm('N', '2026-04-01'))
    return tmp_path


def test_order_newest_first_ties_by_filename_descending(tmp_path):
    rows = _rows(render(load_entries(str(_logbook(tmp_path)))))
    assert [r.split('](')[1].split(')')[0] for r in rows] == [
        '2026-03-01-b.md', '2026-03-01-a.md', '2026-02-01-pipe.md', '2026-01-01-old.md']


def test_structural_files_and_subdirectories_are_not_entries(tmp_path):
    names = entry_files(str(_logbook(tmp_path)))
    assert names == ['2026-01-01-old.md', '2026-02-01-pipe.md', '2026-03-01-a.md', '2026-03-01-b.md']


def test_pipe_is_escaped_and_missing_phase_is_a_dash(tmp_path):
    text = render(load_entries(str(_logbook(tmp_path))))
    row = [r for r in _rows(text) if 'pipe.md' in r][0]
    assert '**ROS \\| UDP panel**' in row
    assert row.startswith('| 2026-02-01 | resolved | — | ')
    assert row.count(' | ') == 4


def test_title_cap_cuts_on_a_word_boundary_with_an_ellipsis():
    short = 'x' * TITLE_CAP
    assert cap_title(short) == short
    long = ' '.join(['word'] * 200)
    capped = cap_title(long)
    assert len(capped) <= TITLE_CAP and capped.endswith(ELLIPSIS)
    assert capped[:-len(ELLIPSIS)].endswith('word')


def test_long_title_is_capped_in_the_row(tmp_path):
    _entry(tmp_path, '2026-05-05-long.md', _fm(' '.join(['long'] * 200), '2026-05-05'))
    row = _rows(render(load_entries(str(tmp_path))))[0]
    title = row.split('**')[1]
    assert len(title) <= TITLE_CAP and title.endswith(ELLIPSIS)


def test_fallbacks_for_irregular_entries(tmp_path):
    # Not valid YAML: an unquoted "@" cannot start a plain scalar (the three historical
    # entries that fail the strict parser do the same with a leading backtick).
    _entry(tmp_path, '2026-06-01-bad-yaml.md',
           '---\ntitle: "Quoted title"\ndate: 2026-06-01\nstatus: done\nphase: "R3"\n'
           'links:\n  - @not yaml\n---\n# Heading\n')
    _entry(tmp_path, '2026-06-02-no-fm.md', 'Intro line\n\n# The heading title\n\nbody\n')
    entries = {e.filename: e for e in load_entries(str(tmp_path))}
    bad = entries['2026-06-01-bad-yaml.md']
    assert (bad.title, bad.date, bad.status, bad.phase) == ('Quoted title', '2026-06-01', 'done', 'R3')
    assert bad.fallbacks == ('lenient-yaml',)
    bare = entries['2026-06-02-no-fm.md']
    assert (bare.title, bare.date, bare.status, bare.phase) == (
        'The heading title', '2026-06-02', None, None)
    assert fallback_counts(list(entries.values())) == {
        'lenient-yaml': 1, 'date-from-filename': 1, 'title-from-heading': 1,
        'no-status': 1, 'no-phase': 1}
    row = [r for r in _rows(render(list(entries.values()))) if 'no-fm' in r][0]
    assert row.startswith('| 2026-06-02 | — | — | **The heading title** | ')


def test_gen_twice_changes_nothing_and_check_exit_codes(tmp_path, capsys):
    repo = str(_logbook(tmp_path))
    index = tmp_path / 'logbook' / 'INDEX.md'
    index.write_text('| hand-written row |\n', encoding='utf-8')
    assert main(['gen', '--repo', repo, '--check']) == 1
    assert index.read_text(encoding='utf-8') == '| hand-written row |\n'
    assert write_index(repo) == [str(index)]
    first = index.read_text(encoding='utf-8')
    assert 'hand-written' not in first and 'do not hand-edit' in first
    assert write_index(repo) == []
    assert index.read_text(encoding='utf-8') == first
    for board in ('active', 'parked', 'archived'):
        (tmp_path / 'plans' / board).mkdir(parents=True)
    assert main(['gen', '--repo', repo]) == 0  # the plan boards too, so --check is clean
    capsys.readouterr()
    assert main(['gen', '--repo', repo, '--check']) == 0
    assert capsys.readouterr().out == ''
    assert index.read_text(encoding='utf-8') == first


def test_no_logbook_dir_writes_nothing(tmp_path):
    assert write_index(str(tmp_path)) == []
    assert not (tmp_path / 'logbook').exists()
