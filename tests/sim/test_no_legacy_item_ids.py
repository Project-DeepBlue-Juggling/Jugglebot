"""The guard: no old global Item ID in the tracked tree (plan ``item-id-per-kind.md`` P5, T-U15).

The contract has three parts: ``DOCUMENTATION_GUIDE.md`` section 2.10 states the
format, ``mapkit/ids.py`` is the one place it is implemented, and this file
fails the default gate when the tree holds the retired form anywhere it is not
allowed to. It is permanent and never ``nightly``: a held branch, a pasted
log line or a habit that reintroduces ``JB-12`` fails the commit that does it.

How a token is judged. Every match of the deliberately broad pattern in
``legacy_id_rules.py`` (any ``jb`` not followed by a letter, any case, so the
lower-case, unhyphenated and padded forms a ``JB-\\d+`` grep misses are caught
too) gets its class from that module's rule table. On top of it this file adds
four owner-decided rules (:data:`GUARD_RULES`) for text that keeps the old form
on purpose. Then:

* ``abbreviation`` (``JB`` meaning Jugglebot: ``JB_OP_*``, ``defer jb``) passes;
* ``frozen`` (filenames, stems, ``Logbook-Entry:`` values, ``plant_id`` keys, the
  scheme-history files, the crosswalk) and ``historical`` (owner Q2, 2026-11-08:
  the placeholders and citations of the old scheme in ``logbook/``, ``map/``
  bodies and ``plans/`` indexes describe the scheme of their day and are left)
  pass only at the per-file counts pinned in :data:`PINS`, so neither can grow
  silently: a new file, or one more token in an old one, fails;
* any other class, or a token no rule takes, fails naming file, line and rule.

Re-pinning after a deliberate change (a new logbook entry that names a file
with ``jb`` in it, say) is ``python tests/sim/test_no_legacy_item_ids.py --pin``,
and the diff of :data:`PINS` is the review.

Runtime: a ``git grep`` prefilter reads only the files and lines that can hold a
token, so the real-tree check costs about what the classification of ~4000
tokens costs, not a read of every tracked line.
"""
from __future__ import annotations

import csv
import os
import re
import subprocess
import sys
from collections import Counter
from typing import Dict, List, NamedTuple, Optional, Tuple

import pytest

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, ROOT)  # so ``--pin``, run as a script, finds the package too
from tests.sim import legacy_id_rules as rules  # noqa: E402

#: The pinned per-file counts, ``class<TAB>path<TAB>count``; regenerated by ``--pin``.
PINS = os.path.join("tests", "sim", "no_legacy_item_ids.tsv")
#: This file, its classifier and its pins name the old form on purpose.
SELF = (os.path.join("tests", "sim", "test_no_legacy_item_ids.py"),
        os.path.join("tests", "sim", "legacy_id_rules.py"), PINS)
PINNED_CLASSES = ("frozen", "historical")
PASS_CLASSES = ("abbreviation",)
#: Classes the Q2 directories keep as history (an Item's own ``id:`` line is never one).
_HISTORICAL_FROM = frozenset({"placeholder", "loose", "citation", "range", "list", "branch"})


class GuardRule(NamedTuple):
    name: str
    cls: str
    path: str                        # regex searched in the path
    line: Optional[str] = None       # regex searched in the line
    from_classes: Optional[frozenset] = None   # the classifier's classes it may take over


#: Ordered; applied only to a token the classifier's rules leave outside abbreviation
#: and frozen. Each is an owner decision of 2026-11-08 (plan P5, brief-p5 Q1/Q2).
GUARD_RULES: Tuple[GuardRule, ...] = (
    # P4's own commit subject, quoted in the blame-ignore list: a commit subject is immutable.
    GuardRule("blame-ignore-subject", "frozen", r"^\.git-blame-ignore-revs$", line=r"^#"),
    # The glossary names the retired form on its Avoid line, as a glossary must.
    GuardRule("glossary-avoid", "frozen", r"^(?:GLOSSARY\.md|docs/glossary\.md)$", line=r"^_Avoid"),
    # Owner Q1: test identifiers named after the Item they test stay as written.
    GuardRule("legacy-test-identifier", "frozen",
              r"^tests/(?:firmware/native/test_fault_machine\.cpp|firmware/native/test_leg_interp\.cpp"
              r"|ros/test_skill_node\.py)$", from_classes=frozenset({"loose"})),
    # Owner Q2: the old scheme's text in the record of its day.
    GuardRule("historical-record", "historical",
              r"^(?:logbook/|plans/archived/|plans/(?:active|parked|archived)/INDEX\.md$|map/)",
              from_classes=_HISTORICAL_FROM),
)
_GUARD = [(r, re.compile(r.path), re.compile(r.line) if r.line else None) for r in GUARD_RULES]


class Verdict(NamedTuple):
    file: str
    line: int
    token: str
    cls: str        # the final class; "UNCLASSIFIED" when no rule takes it
    rule: str


def judge(tok: "rules.Token") -> Verdict:
    """The classifier's class for ``tok``, then the guard's rules (:data:`GUARD_RULES`)."""
    rule = rules.match_rule(tok)
    cls, name = (rule.cls, rule.name) if rule is not None else ("UNCLASSIFIED", "-")
    if cls not in PASS_CLASSES + ("frozen",) and name != "frontmatter-id":
        for g, path, line in _GUARD:
            if not path.search(tok.file) or (line and not line.search(tok.text)):
                continue
            if g.from_classes is not None and cls not in g.from_classes:
                continue
            cls, name = g.cls, g.name
            break
    return Verdict(tok.file, tok.line, tok.token, cls, name)


def candidate_files(root: str) -> List[str]:
    """Tracked text files that hold ``jb`` in any case (a superset of the token files):
    one ``git grep``, then the classifier's skip rule."""
    r = subprocess.run(["git", "grep", "-I", "-l", "-i", "-z", "-e", "jb"], cwd=root,
                       capture_output=True)
    if r.returncode not in (0, 1):
        raise RuntimeError("git grep failed: %s" % r.stderr.decode("utf-8", "replace"))
    files = r.stdout.decode("utf-8", "surrogateescape").split("\0")
    return sorted(f for f in files if f and rules.skip_reason(root, f) is None)


def scan(root: str) -> List[Verdict]:
    """Every broad-pattern token of the tracked tree under ``root``, judged."""
    out: List[Verdict] = []
    for rel in candidate_files(root):
        if rel in SELF:
            continue
        with open(os.path.join(root, rel), "rb") as fh:
            lines = fh.read().decode("utf-8", "replace").split("\n")
        for n, text in enumerate(lines, 1):
            if "jb" not in text.lower():
                continue
            for tok in rules.line_tokens(rel, n, text):
                out.append(judge(tok))
    return out


def counts(verdicts: List[Verdict]) -> Dict[Tuple[str, str], int]:
    return dict(Counter((v.cls, v.file) for v in verdicts if v.cls in PINNED_CLASSES))


def read_pins(root: str) -> Dict[Tuple[str, str], int]:
    path = os.path.join(root, PINS)
    if not os.path.isfile(path):
        return {}
    with open(path, newline="", encoding="utf-8") as fh:
        return {(r["class"], r["path"]): int(r["count"]) for r in csv.DictReader(fh, delimiter="\t")}


def write_pins(root: str, pinned: Dict[Tuple[str, str], int]) -> str:
    path = os.path.join(root, PINS)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, delimiter="\t", lineterminator="\n")
        w.writerow(["class", "path", "count"])
        for (cls, rel), n in sorted(pinned.items()):
            w.writerow([cls, rel, n])
    return path


def problems(root: str) -> List[str]:
    """Every reason the tree fails the guard, one line each; empty when it passes."""
    verdicts = scan(root)
    out = ["%s:%d: %s  [%s, rule %s]" % (v.file, v.line, v.token, v.cls, v.rule)
           for v in verdicts if v.cls not in PASS_CLASSES + PINNED_CLASSES]
    have, want = counts(verdicts), read_pins(root)
    for key in sorted(set(have) | set(want)):
        if have.get(key, 0) != want.get(key, 0):
            lines = ", ".join("%d" % v.line for v in verdicts if (v.cls, v.file) == key)
            out.append("%s: %d %s tokens, %d pinned in %s (lines: %s)" % (
                key[1], have.get(key, 0), key[0], want.get(key, 0), PINS, lines or "none"))
    return out


