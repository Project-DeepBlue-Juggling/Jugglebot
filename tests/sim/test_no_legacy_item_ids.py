def _rule_of(text: str) -> Dict[str, Optional[str]]:
    out: Dict[str, Optional[str]] = {}
    for t in rules.line_tokens("docs/x.md", 1, text):
        r = rules.match_rule(t)
        out[t.token] = r.name if r else None
    return out


def test_a_date_suffix_is_not_a_hyphenated_name_but_a_letter_hyphen_is():
    by = _rule_of("delete `-11-05-JB-163` and Higher-throws-with-JB-144-update and gate-JB-141-run1")
    assert by["JB-163"] != "inside-hyphenated-name", by
    assert by["JB-144-update"] == "inside-hyphenated-name", by
    assert by["JB-141-run1"] == "inside-hyphenated-name", by


def test_a_letter_placeholder_in_a_filename_is_not_frozen_by_a_path_rule(tmp_path):
    root = _tree(tmp_path, {".claude/commands/x.md": ("see JB-n-question.md and JB-<n>-question.md here\n"
                                                      "real logbook/2026-11-01-jb1-thing.md and jb-12-fix.md stay\n")})
    cls = {t[1]: t[2] for t in _judged(root, ".claude/commands/x.md")}
    assert cls["JB-n-question"] == "placeholder" and cls["JB-<n>-question"] == "placeholder", cls
    assert cls["jb1-thing"] == "frozen" and cls["jb-12-fix"] == "frozen", cls


def test_only_text_files_are_read(tmp_path):
    root = _tree(tmp_path, {"docs/a.md": "x JB-1\n", "pic.png": "jb\n", "bin.dat": "jb\0\n"})
    os.symlink("docs/a.md", os.path.join(root, "link.md"))
    subprocess.run(["git", "add", "link.md"], cwd=root, check=True)
    assert rules.skip_reason(root, "pic.png") == "suffix"
    assert rules.skip_reason(root, "bin.dat") == "binary"
    assert rules.skip_reason(root, "link.md") == "symlink"
    assert rules.skip_reason(root, "docs/a.md") is None
    assert candidate_files(root) == ["docs/a.md"]


