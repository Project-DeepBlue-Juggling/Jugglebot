# -*- coding: utf-8 -*-
"""Drift test for the generated topic-choreography map.

``ros_ws/docs/choreography.md`` is generated by
``tools/gen_choreography_map.py``.  This test regenerates it into ``tmp_path``
and diffs against the committed copy, so a node that gains, loses or renames a
publisher/subscriber/service/action reddens the suite until the doc is
regenerated.

It also pins the *honesty* properties the map depends on: every name is either
resolved or explicitly marked ``UNRESOLVED(...)``, the "Python-node graph only"
banner is present, and the hand-ownership latch / multi-publisher wires still
carry their contract notes.

The generator is pure ``ast`` — it never imports rclpy — so this file is safe
under the mocked-ROS conftest.
"""

from __future__ import annotations

import ast
import difflib
import functools
import os
import textwrap

import pytest

from tools.gen_choreography_map import (
    HAND_OWNERSHIP_LATCH_TOPICS,
    MULTI_PUBLISHER_TOPICS,
    NOT_LAUNCHED_NODES,
    _CONTRACT_NOTES,
    _NODE_DIR,
    _DEFAULT_OUT,
    generate,
    main,
    scan_nodes,
    scan_file,
)

#: ``_NODE_DIR`` is ``ros_ws/src/jugglebot/jugglebot``; the launch file lives one
#: level up, in the package root.
_LAUNCH_FILE = os.path.join(
    os.path.dirname(_NODE_DIR), 'launch', 'jugglebot_launch.py')


@functools.lru_cache(maxsize=1)
def _scan():
    """Memoised package scan — several tests need it and the walk is ~0.6 s."""
    return tuple(scan_nodes())


def _committed_text():
    with open(_DEFAULT_OUT, 'r', encoding='utf-8') as handle:
        return handle.read()


# ---------------------------------------------------------------------------
# Drift
# ---------------------------------------------------------------------------

def test_committed_doc_matches_regeneration(tmp_path):
    """The committed map equals a fresh generation from the node sources."""
    out = tmp_path / 'choreography.md'
    assert main(['--out', str(out)]) == 0
    fresh = out.read_text(encoding='utf-8')
    committed = _committed_text()

    if fresh != committed:
        diff = '\n'.join(difflib.unified_diff(
            committed.splitlines(), fresh.splitlines(),
            fromfile='committed ros_ws/docs/choreography.md',
            tofile='regenerated', lineterm=''))
        pytest.fail(
            'ros_ws/docs/choreography.md is stale — the node graph changed.\n'
            'Regenerate with: python tools/gen_choreography_map.py\n\n' + diff)


def test_generation_is_deterministic():
    """Two runs produce byte-identical text (stable sort order)."""
    assert generate() == generate()


def test_check_flag_detects_drift(tmp_path):
    stale = tmp_path / 'choreography.md'
    stale.write_text('# not the map\n', encoding='utf-8')
    assert main(['--out', str(stale), '--check']) == 1
    assert main(['--out', str(_DEFAULT_OUT), '--check']) == 0


def test_check_flag_reports_missing_file(tmp_path):
    assert main(['--out', str(tmp_path / 'nope.md'), '--check']) == 1


