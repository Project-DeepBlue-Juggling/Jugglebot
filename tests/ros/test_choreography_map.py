def test_multi_publisher_topics_are_annotated():
    """The two by-design multi-publisher topics really have >1 publisher, and say so."""
    text = _committed_text()
    publishers = {}
    for endpoint in _scan():
        if endpoint.kind == 'publisher':
            publishers.setdefault(endpoint.name, set()).add(endpoint.node)

    for name in MULTI_PUBLISHER_TOPICS:
        assert len(publishers.get(name, ())) >= 2, (
            name + ' no longer has multiple publishers — update the contract note')
        assert name in _CONTRACT_NOTES
        assert 'MULTI-PUBLISHER by design' in _CONTRACT_NOTES[name]
        assert '### `' + name + '`' in text


def test_hand_ownership_latch_topics_are_annotated():
    text = _committed_text()
    assert len(HAND_OWNERSHIP_LATCH_TOPICS) == 5
    for index, name in enumerate(HAND_OWNERSHIP_LATCH_TOPICS, start=1):
        note = _CONTRACT_NOTES.get(name)
        assert note is not None, name + ' lost its contract note'
        assert 'HAND-OWNERSHIP LATCH (%d/5)' % index in note
        assert '### `' + name + '`' in text


def _launched_jugglebot_executables():
    """Executables the launch file starts from the ``jugglebot`` package.

    Parsed with ``ast`` rather than imported: importing the launch file pulls
    ``launch``/``launch_ros``, which are not available under the mocked-ROS
    conftest.
    """
    with open(_LAUNCH_FILE, 'r', encoding='utf-8') as handle:
        tree = ast.parse(handle.read(), filename=_LAUNCH_FILE)
    out = set()
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Call)
                and isinstance(node.func, ast.Name) and node.func.id == 'Node'):
            continue
        kwargs = {}
        for keyword in node.keywords:
            if isinstance(keyword.value, ast.Constant):
                kwargs[keyword.arg] = keyword.value.value
        if kwargs.get('package') == 'jugglebot' and kwargs.get('executable'):
            out.add(kwargs['executable'])
    return out


def test_not_launched_nodes_match_launch_file():
    """The ``(not launched)`` tag set is exactly the scanned-minus-launched set.

    Both directions matter and both have bitten this repo's docs before:
    a node that gets re-enabled in the launch file must lose its tag (else the
    map understates the live graph), and a node that gets dropped from the
    launch file must gain one (else the map presents a parked node as a live
    consumer — what Phase 3's dormancy did to eight wires).
    """
    launched = _launched_jugglebot_executables()
    assert launched, 'parsed no jugglebot Node() entries from ' + _LAUNCH_FILE

    scanned = {e.node for e in _scan()}
    assert set(NOT_LAUNCHED_NODES) == scanned - launched, (
        'NOT_LAUNCHED_NODES is stale: scanned=%r launched=%r'
        % (sorted(scanned), sorted(launched)))
    assert not set(NOT_LAUNCHED_NODES) & launched


def test_not_launched_nodes_are_tagged_in_the_doc():
    """Every rendered mention of a parked node carries the marker."""
    text = _committed_text()
    for name in NOT_LAUNCHED_NODES:
        occurrences = text.count('`' + name + '`')
        tagged = text.count('`' + name + '` (not launched)')
        assert occurrences, name + ' does not appear in the map at all'
        # The preamble names both nodes in prose; every graph-line mention is tagged.
        assert tagged >= occurrences - 1, (
            '%s appears untagged in the map (%d mentions, %d tagged)'
            % (name, occurrences, tagged))
    assert 'not launched' in text.split('## Topics', 1)[0], (
        'the preamble must explain the (not launched) tag')


def test_annotated_topics_all_exist_in_the_graph():
    """No contract note points at a wire that no longer exists."""
    names = {e.name for e in _scan()}
    missing = sorted(set(_CONTRACT_NOTES) - names)
    assert not missing, 'contract notes for non-existent endpoints: %r' % (missing,)


