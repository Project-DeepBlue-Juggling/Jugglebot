def _write_node(tmp_path, body, name='fake_node.py'):
    path = tmp_path / name
    path.write_text(textwrap.dedent(body), encoding='utf-8')
    return str(path)


def test_resolves_string_literal(tmp_path):
    path = _write_node(tmp_path, """
        class N:
            def __init__(self):
                self.create_publisher(Bool, 'a/b', 10)
    """)
    (endpoint,) = scan_file(path)
    assert (endpoint.name, endpoint.kind, endpoint.provenance) == ('a/b', 'publisher', 'literal')


def test_resolves_module_constant(tmp_path):
    path = _write_node(tmp_path, """
        TOPIC = 'from/const'
        class N:
            def __init__(self):
                self.create_subscription(Bool, TOPIC, self.cb, 10)
    """)
    (endpoint,) = scan_file(path)
    assert endpoint.name == 'from/const'
    assert endpoint.provenance == 'constant'


def test_attribute_expression_is_refused_not_guessed(tmp_path):
    """``self.X`` must NOT be answered from a same-named module/class constant.

    The index keys constants by BARE name, so looking up ``node.attr`` conflated
    an *instance* attribute with an unrelated module-level constant and reported
    provenance ``constant`` — a confident wrong wire, which is precisely the
    failure the honesty rule exists to prevent.  Resolving this shape correctly
    needs real instance-attribute tracking; until someone does that work the
    resolver refuses, and the hole is visible in the "Unresolved names" section.

    Both sub-cases below silently mis-resolved before 2026-08-01.
    """
    shadowed = _write_node(tmp_path, """
        TOPIC = 'module/level'
        class N:
            def __init__(self):
                self.TOPIC = 'instance/level'
                self.create_publisher(Bool, self.TOPIC, 10)
    """, name='shadowed.py')
    (endpoint,) = scan_file(shadowed)
    assert endpoint.provenance == 'unresolved', endpoint.name
    assert endpoint.name == 'UNRESOLVED(self.TOPIC)'

    classvar = _write_node(tmp_path, """
        class N:
            TOPIC = 'from/classvar'
            def __init__(self):
                self.create_publisher(Bool, self.TOPIC, 10)
    """, name='classvar.py')
    (endpoint,) = scan_file(classvar)
    assert endpoint.provenance == 'unresolved', endpoint.name


def test_nested_function_binding_does_not_leak_to_enclosing_scope(tmp_path):
    """A literal bound only inside a nested ``def`` must not resolve an outer call.

    The local index used to be built with ``ast.walk``, which descends into
    nested functions, so a helper's binding leaked upward and answered a call
    site it never reaches — with provenance ``literal``, i.e. maximum confidence.
    """
    path = _write_node(tmp_path, """
        class N:
            def __init__(self):
                self.create_publisher(Bool, topic, 10)

                def helper():
                    topic = 'inner/only'
                    return topic
    """)
    (endpoint,) = scan_file(path)
    assert endpoint.provenance == 'unresolved', endpoint.name
    assert endpoint.name == 'UNRESOLVED(topic)'


def test_nested_function_keeps_its_own_bindings(tmp_path):
    """The fix must not blind a nested function to its OWN locals."""
    path = _write_node(tmp_path, """
        class N:
            def __init__(self):
                def helper(self):
                    topic = 'inner/own'
                    self.create_publisher(Bool, topic, 10)
    """)
    (endpoint,) = scan_file(path)
    assert (endpoint.name, endpoint.provenance) == ('inner/own', 'literal')


