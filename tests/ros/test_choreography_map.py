def test_rebound_local_is_refused_not_guessed(tmp_path):
    """A local bound to two different literals must not resolve to either.

    The index is flow-INsensitive: it cannot tell which binding reaches the call
    site.  Picking the last one would print a confident, wrong wire — the exact
    failure mode this map is supposed to make impossible.
    """
    path = _write_node(tmp_path, """
        class N:
            def __init__(self):
                topic = 'first/name'
                self.create_publisher(Bool, topic, 10)
                topic = 'second/name'
                self.create_publisher(Bool, topic, 10)
    """)
    endpoints = scan_file(path)
    assert len(endpoints) == 2
    for endpoint in endpoints:
        assert endpoint.provenance == 'unresolved', endpoint.name
        assert endpoint.name.startswith('UNRESOLVED(')


