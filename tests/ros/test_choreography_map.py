def test_scan_skips_test_and_cache_directories(tmp_path):
    pkg_tests = tmp_path / 'tests'
    pkg_tests.mkdir()
    _write_node(pkg_tests, """
        class N:
            def __init__(self):
                self.create_publisher(Bool, 'from/tests', 10)
    """, name='test_thing.py')
    cache = tmp_path / '__pycache__'
    cache.mkdir()
    (cache / 'stale.py').write_text("x.create_publisher(B, 'from/cache', 1)\n",
                                    encoding='utf-8')
    assert scan_nodes(str(tmp_path)) == []


