def test_banner_present():
    text = _committed_text()
    assert 'Python-node graph only' in text
    assert 'GUI/rosbridge consumers are NOT included' in text


def test_no_endpoint_name_is_silently_guessed():
    """Every unresolved name carries the UNRESOLVED marker and is listed."""
    text = _committed_text()
    unresolved = [e for e in _scan() if e.provenance == 'unresolved']
    for endpoint in unresolved:
        assert endpoint.name.startswith('UNRESOLVED('), endpoint.name
        assert endpoint.name in text
    section = text.split('## Unresolved names', 1)[1]
    if not unresolved:
        assert 'every endpoint name resolved to a literal' in section


def test_parameter_derived_names_are_tagged():
    """A name that came from a ROS-parameter default is marked as such.

    ``trajectory_node`` subscribes to ``str(self.get_parameter('control_mode_topic')
    .value)``.  The map resolves it to the declared default but must say so —
    a launch override would change the real wire.
    """
    endpoints = [e for e in _scan() if e.provenance.startswith('param:')]
    assert endpoints, 'expected at least the control_mode_topic parameter wire'
    text = _committed_text()
    for endpoint in endpoints:
        assert '`' + endpoint.provenance + '`' in text


