class OdriveApi:
    """The bits of the odrive package this script uses.

    Imported lazily so the module stays importable (and unit-testable) on a box
    without the odrive package or without hardware attached.
    """

    def __init__(self) -> None:
        try:
            import odrive
            from odrive.enums import AxisState, ODriveError, ProcedureResult
            from odrive.legacy_config import backup_config, restore_config
            from odrive.libodrive import DeviceLostException
        except ImportError as exc:
            raise SystemExit(
                'could not import the odrive package ({}).\n'
                'Activate the project venv first:\n'
                '    source ~/Desktop/PDJ_venv/venv/bin/activate'.format(exc)
            )
        self.odrive = odrive
        self.backup_config = backup_config
        self.restore_config = restore_config
        self.DeviceLostException = DeviceLostException
        self.AxisState = AxisState
        self.ProcedureResult = ProcedureResult
        self.ODriveError = ODriveError

        # The state machine below drives raw ints so the module imports without
        # this package; assert they still mean what they meant on 0.6.10.
        assert int(AxisState.IDLE) == AXIS_STATE_IDLE
        assert int(AxisState.FULL_CALIBRATION_SEQUENCE) == AXIS_STATE_FULL_CALIBRATION_SEQUENCE
        assert int(ProcedureResult.SUCCESS) == PROCEDURE_RESULT_SUCCESS
        assert int(ProcedureResult.BUSY) == PROCEDURE_RESULT_BUSY

    def procedure_name(self, value: int) -> str:
        try:
            return self.ProcedureResult(value).name
        except Exception:
            return 'UNKNOWN({})'.format(value)

    def error_name(self, bitmask: int) -> str:
        if not bitmask:
            return 'none'
        try:
            return str(self.ODriveError(bitmask))
        except Exception:
            return hex(bitmask)


def usb_serial(odrv: Any) -> str:
    """The USB serial string, which is what ``find_sync`` matches on.

    Deliberately ``_dev.serial_number`` and not ``odrv.serial_number``: the
    latter is the firmware's uint64 property, while discovery keys off the USB
    descriptor string in ``RuntimeDevice.serial_number``.
    """
    return odrv._dev.serial_number


def read_node_id(odrv: Any) -> int:
    return int(odrv.axis0.config.can.node_id)


def read_fw_version(odrv: Any) -> Optional[str]:
    try:
        return '{}.{}.{}'.format(
            odrv.fw_version_major, odrv.fw_version_minor, odrv.fw_version_revision
        )
    except Exception:
        return None


def is_alive(odrv: Any) -> bool:
    """True if the handle still answers a read."""
    try:
        read_node_id(odrv)
        return True
    except Exception:
        return False


def discover(api: OdriveApi, count: int, timeout: float) -> List[Any]:
    """Block until ``count`` drives are connected, then return them."""
    print('Waiting for {} ODrives on USB (timeout {:.0f} s)...'.format(count, timeout))
    try:
        drives = api.odrive.find_sync(count=count, timeout=timeout)
    except TimeoutError:
        raise SystemExit(
            'timed out waiting for {} ODrives. Check power and USB, or pass '
            '--expect <n> if fewer are attached.'.format(count)
        )
    return list(drives)


def call_tolerating_reboot(odrv: Any, api: OdriveApi, name: str) -> bool:
    """Call a function that is expected to reboot the drive.

    Returns True if the drive went away (the call landed and the reboot began).
    """
    if not hasattr(odrv, name):
        # Never silently skip the erase: "reflashed without erasing" is a
        # different operation from the one the caller asked for.
        raise SystemExit(
            'this firmware exposes no {}() — refusing to continue, since the '
            'erase step cannot be verified.'.format(name))
    try:
        getattr(odrv, name)()
    except api.DeviceLostException:
        return True
    except Exception as exc:
        # Not necessarily fatal: some transports surface the lost connection as
        # a generic error on the reboot ack path. Probe rather than assume.
        print('      note: {}() raised {}: {}'.format(name, type(exc).__name__, exc))
    return not is_alive(odrv)


class CalibrationOutcome:
    """What FULL_CALIBRATION_SEQUENCE did on one axis."""

    def __init__(self) -> None:
        self.started = False
        self.timed_out = False
        self.result: Optional[int] = None
        self.result_name = 'not run'
        self.active_errors = 0
        self.disarm_reason = 0
        self.elapsed_s = 0.0

    @property
    def ok(self) -> bool:
        return (
            self.started
            and not self.timed_out
            and self.result == PROCEDURE_RESULT_SUCCESS
            and self.active_errors == 0
        )

    def __str__(self) -> str:
        if self.timed_out:
            return 'TIMED OUT after {:.0f} s (last result {})'.format(
                self.elapsed_s, self.result_name)
        if not self.started:
            return 'never started ({})'.format(self.result_name)
        return '{} in {:.1f} s'.format(self.result_name, self.elapsed_s)


def run_full_calibration(api: OdriveApi, odrv: Any, timeout_s: float) -> CalibrationOutcome:
    """Run FULL_CALIBRATION_SEQUENCE on axis0 and block until it finishes.

    THIS MOVES THE MOTOR. Never returns while the axis is still calibrating: an
    early return would let the caller save the config mid-procedure.
    """
    axis = odrv.axis0
    outcome = CalibrationOutcome()

    errors = int(axis.active_errors)
    if errors:
        # A latched error makes the state request a no-op, which would otherwise
        # look like "calibration finished instantly".
        print('      clearing latched active_errors: {}'.format(api.error_name(errors)))
        try:
            odrv.clear_errors()
        except Exception as exc:
            print('      note: clear_errors() raised {}: {}'.format(type(exc).__name__, exc))

    state = int(axis.current_state)
    if state != AXIS_STATE_IDLE:
        raise SystemExit(
            'axis is in state {}, not IDLE — refusing to start a calibration on '
            'an axis that is already doing something.'.format(state))

    start = time.time()
    axis.requested_state = AXIS_STATE_FULL_CALIBRATION_SEQUENCE

    # Wait for it to actually begin. procedure_result holds the PREVIOUS
    # outcome until the new procedure starts, so polling it alone can read a
    # stale SUCCESS and declare victory before the motor has moved.
    grace_deadline = time.time() + CALIB_START_GRACE_S
    while time.time() < grace_deadline:
        if (int(axis.current_state) != AXIS_STATE_IDLE
                or int(axis.procedure_result) == PROCEDURE_RESULT_BUSY):
            outcome.started = True
            break
        time.sleep(CALIB_POLL_S)

    if not outcome.started:
        outcome.result = int(axis.procedure_result)
        outcome.result_name = api.procedure_name(outcome.result)
        outcome.active_errors = int(axis.active_errors)
        outcome.disarm_reason = int(axis.disarm_reason)
        outcome.elapsed_s = time.time() - start
        return outcome

    deadline = time.time() + timeout_s
    while True:
        idle = int(axis.current_state) == AXIS_STATE_IDLE
        settled = int(axis.procedure_result) != PROCEDURE_RESULT_BUSY
        if idle and settled:
            break
        if time.time() > deadline:
            outcome.timed_out = True
            try:
                axis.requested_state = AXIS_STATE_IDLE  # stop the motor
            except Exception:
                pass
            break
        time.sleep(CALIB_POLL_S)

    outcome.elapsed_s = time.time() - start
    outcome.result = int(axis.procedure_result)
    outcome.result_name = api.procedure_name(outcome.result)
    outcome.active_errors = int(axis.active_errors)
    outcome.disarm_reason = int(axis.disarm_reason)
    return outcome


def wait_for_drive(api: OdriveApi, serial: str, timeout: float = REBOOT_TIMEOUT_S) -> Any:
    """Wait for ``serial`` to reappear after a reboot and answer a read."""
    time.sleep(REBOOT_SETTLE_S)  # let the old handle be reaped before re-asking
    deadline = time.time() + timeout
    while True:
        remaining = deadline - time.time()
        if remaining <= 0:
            raise SystemExit(
                'ODrive {} did not come back within {:.0f} s of a reboot. Its '
                'config may be half-written — restore from the backup in the '
                'backup directory before using it.'.format(serial, timeout)
            )
        try:
            odrv = api.odrive.find_sync(serial_number=serial, timeout=remaining)
        except TimeoutError:
            continue
        if is_alive(odrv):
            return odrv
        time.sleep(0.5)


