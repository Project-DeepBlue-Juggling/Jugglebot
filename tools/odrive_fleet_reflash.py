def parse_args(argv: Optional[Sequence[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description='Erase and reflash the leg ODrives, preserving CAN node IDs.',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog='Run with --dry-run first if you want to see the diff before erasing.',
    )
    parser.add_argument('--config', default=DEFAULT_TARGET_CONFIG,
                        help='config JSON to flash (default: the leg snapshot)')
    parser.add_argument('--backup-dir', default=None,
                        help='where to write the map and backups '
                             '(default: temp/odrive_configs/<timestamp>/)')
    parser.add_argument('--dry-run', action='store_true',
                        help='discover, record the map, back up and diff — erase nothing')
    parser.add_argument('--only', default=None,
                        help='comma-separated node IDs to process (default: all legs)')
    parser.add_argument('--map', default=None,
                        help='resolve node IDs from a previously written fleet_map.json '
                             'instead of reading them off the drives')
    parser.add_argument('--expect', type=int, default=len(LEG_NODE_IDS) + len(PROTECTED_NODE_IDS),
                        help='number of drives to wait for on USB (default: %(default)s)')
    parser.add_argument('--timeout', type=float, default=DISCOVERY_TIMEOUT_S,
                        help='discovery timeout in seconds (default: %(default)s)')
    parser.add_argument('--ignore-restore-errors', action='store_true',
                        help='keep going when a property write fails (default: stop)')
    parser.add_argument('--force', action='store_true',
                        help='proceed despite conflicting processes or a suspect config file')
    return parser.parse_args(argv)


def resolve_targets(node_by_serial: Dict[str, int], only: Optional[str]) -> List[int]:
    """Node IDs to process, in ascending order."""
    if only is None:
        wanted = list(LEG_NODE_IDS)
    else:
        try:
            wanted = [int(token) for token in only.split(',') if token.strip()]
        except ValueError:
            raise SystemExit('--only takes comma-separated integers, e.g. --only 0,3')
        illegal = [i for i in wanted if i not in LEG_NODE_IDS]
        if illegal:
            raise SystemExit(
                '--only {} includes node IDs outside the leg set {}. Node {} is '
                'protected and is never written to.'.format(
                    illegal, list(LEG_NODE_IDS), list(PROTECTED_NODE_IDS)))
    present = set(node_by_serial.values())
    missing = [i for i in wanted if i not in present]
    if missing:
        raise SystemExit('requested node IDs {} are not on USB'.format(missing))
    # Deduplicated: a drive listed twice would be processed twice, and the
    # second pass would run against the handle the first pass's reboot killed.
    return sorted(set(wanted))


def load_fleet_map(path: str) -> Dict[str, int]:
    with open(path) as handle:
        data = json.load(handle)
    return {entry['serial']: int(entry['node_id']) for entry in data['drives']}


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = parse_args(argv)

    # --- preflight: the target file -------------------------------------
    if not os.path.exists(args.config):
        raise SystemExit('target config not found: {}'.format(args.config))
    with open(args.config) as handle:
        target_nested = json.load(handle)
    flat_target = flatten_config(target_nested)
    patch_node_id(target_nested, 0)  # fail now if the file has no node_id path

    problems = check_target_is_leg_config(flat_target)
    if problems:
        for line in problems:
            print('CONFIG WARNING: {}'.format(line), file=sys.stderr)
        if not args.force:
            raise SystemExit('refusing to flash this file to the legs (--force overrides)')

    # --- preflight: nothing else owning the drives ----------------------
    conflicts = find_conflicting_processes(read_proc_cmdlines())
    if conflicts:
        print('CONFLICTING PROCESSES:', file=sys.stderr)
        for pattern, cmd in conflicts:
            print('  [{}] {}'.format(pattern, cmd[:160]), file=sys.stderr)
        if not args.force:
            raise SystemExit(
                'stop the ROS stack / odrivetool / ODrive GUI first: they command '
                'or claim these drives while they are being reflashed '
                '(--force overrides)')

    backup_dir = args.backup_dir or os.path.join(
        DEFAULT_BACKUP_ROOT, datetime.now().strftime('%Y%m%d_%H%M%S'))
    os.makedirs(backup_dir, exist_ok=True)

    print('target config : {}'.format(os.path.relpath(args.config, _PROJECT_ROOT)))
    print('               {} config properties'.format(len(flat_target)))
    print('backup dir    : {}'.format(os.path.relpath(backup_dir, _PROJECT_ROOT)))
    print('legs          : {}   protected: {}'.format(list(LEG_NODE_IDS), list(PROTECTED_NODE_IDS)))

    api = OdriveApi()
    drives = discover(api, args.expect, args.timeout)

    # --- step 1: record the serial -> node ID mapping -------------------
    by_serial: Dict[str, Any] = {}
    node_by_serial: Dict[str, int] = {}
    fw_by_serial: Dict[str, Optional[str]] = {}
    mapped = load_fleet_map(args.map) if args.map else None

    for odrv in drives:
        serial = usb_serial(odrv)
        by_serial[serial] = odrv
        fw_by_serial[serial] = read_fw_version(odrv)
        if mapped is not None:
            if serial not in mapped:
                print('  USB {}: not in the supplied map — ignoring'.format(serial))
                continue
            node_by_serial[serial] = mapped[serial]
        else:
            node_by_serial[serial] = read_node_id(odrv)

    print('\nUSB serial        node ID  firmware  role')
    for serial, node_id in sorted(node_by_serial.items(), key=lambda kv: kv[1]):
        role = 'PROTECTED' if node_id in PROTECTED_NODE_IDS else (
            'leg' if node_id in LEG_NODE_IDS else 'unknown')
        print('  {:<16}  {:>5}    {:<8}  {}'.format(
            serial, node_id, fw_by_serial.get(serial) or '?', role))
    if mapped is not None:
        print('(node IDs from {}, not read off the drives)'.format(args.map))

    errors, warnings = validate_fleet(node_by_serial)
    for line in warnings:
        print('WARNING: {}'.format(line), file=sys.stderr)
    if errors:
        for line in errors:
            print('FLEET ERROR: {}'.format(line), file=sys.stderr)
        raise SystemExit('refusing to touch anything while the fleet looks like this')

    map_path = os.path.join(backup_dir, 'fleet_map.json')
    with open(map_path, 'w') as handle:
        json.dump({
            'recorded': datetime.now().isoformat(timespec='seconds'),
            'target_config': os.path.relpath(args.config, _PROJECT_ROOT),
            'node_id_source': args.map if mapped is not None else 'read from drives',
            'drives': [
                {
                    'serial': serial,
                    'node_id': node_id,
                    'fw_version': fw_by_serial.get(serial),
                    'role': 'protected' if node_id in PROTECTED_NODE_IDS else 'leg',
                }
                for serial, node_id in sorted(node_by_serial.items(), key=lambda kv: kv[1])
            ],
        }, handle, indent=2)
    print('\nmapping recorded -> {}'.format(os.path.relpath(map_path, _PROJECT_ROOT)))

    targets = resolve_targets(node_by_serial, args.only)
    serial_of = {node_id: serial for serial, node_id in node_by_serial.items()}

    # --- dry run: back up and diff, touch nothing -----------------------
    if args.dry_run:
        print('\nDRY RUN — backing up and diffing, nothing will be erased.')
        for node_id in targets:
            serial = serial_of[node_id]
            odrv = by_serial[serial]
            path = os.path.join(backup_dir, 'current_node{}_{}.json'.format(node_id, serial))
            current = write_backup(api, odrv, path)
            rows = diff_flat(current, flatten_config(patch_node_id(target_nested, node_id)))
            print('\n  node {} (USB {}): {} of {} properties differ from the target'.format(
                node_id, serial, len(rows), len(flat_target)))
            for prop, actual, want in rows:
                print('      {}: drive={!r} target={!r}'.format(prop, actual, want))
        print('\nBackups and the map are in {}'.format(os.path.relpath(backup_dir, _PROJECT_ROOT)))
        print('Rerun without --dry-run to erase and reflash.')
        return 0

    # --- steps 2-5, one drive at a time ---------------------------------
    print('\nProcessing {} drive(s): {}'.format(len(targets), targets))
    results: List[DriveResult] = []
    for node_id in targets:
        results.append(process_drive(
            api, by_serial[serial_of[node_id]], node_id, target_nested,
            backup_dir, args.ignore_restore_errors,
        ))

    # --- summary --------------------------------------------------------
    print('\n=== summary ==========================================')
    print('node  USB serial        node ID after  restore errs  verify diffs  result')
    for res in results:
        print('{:>4}  {:<16}  {:>13}  {:>12}  {:>12}  {}'.format(
            res.node_id, res.serial,
            '?' if res.node_id_after is None else res.node_id_after,
            len(res.restore_errors), len(res.verify_rows),
            'OK' if res.ok else 'CHECK'))
    print('\nbackups + map: {}'.format(os.path.relpath(backup_dir, _PROJECT_ROOT)))

    failed = [res for res in results if not res.ok]
    if failed:
        print('\n{} drive(s) need attention: {}'.format(
            len(failed), [res.node_id for res in failed]), file=sys.stderr)
        return 1

    print('\nAll {} drive(s) reflashed and verified.'.format(len(results)))
    print('Per-motor calibration (index offset, phase R/L) now carries the '
          'snapshot\'s values — HOME every leg before arming it.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
