class DriveResult:
    def __init__(self, node_id: int, serial: str) -> None:
        self.node_id = node_id
        self.serial = serial
        self.backup_path: Optional[str] = None
        self.restore_errors: List[str] = []
        self.verify_rows: List[Tuple[str, Any, Any]] = []
        self.node_id_after: Optional[int] = None
        self.status = 'not started'

    @property
    def ok(self) -> bool:
        return (
            self.status == 'done'
            and not self.restore_errors
            and not self.verify_rows
            and self.node_id_after == self.node_id
        )


def write_backup(api: OdriveApi, odrv: Any, path: str) -> Dict[str, Any]:
    """Read the drive's config and write it in ``odrivetool backup-config`` form."""
    config = api.backup_config(odrv)
    with open(path, 'w') as handle:
        json.dump(config, handle, indent=2)
    return config


def process_drive(
    api: OdriveApi,
    odrv: Any,
    node_id: int,
    target_nested: Dict[str, Any],
    backup_dir: str,
    ignore_restore_errors: bool,
) -> DriveResult:
    """Back up, erase, reflash and verify one drive."""
    serial = usb_serial(odrv)
    result = DriveResult(node_id, serial)
    print('\n--- node {} (USB {}) -----------------------------------'.format(node_id, serial))

    # 1. Back up before anything is destroyed.
    result.backup_path = os.path.join(
        backup_dir, 'pre_erase_node{}_{}.json'.format(node_id, serial))
    write_backup(api, odrv, result.backup_path)
    print('  backed up  -> {}'.format(os.path.relpath(result.backup_path, _PROJECT_ROOT)))

    # 2. Erase NVM, then reboot so RAM holds defaults too.
    print('  erasing configuration...')
    if not call_tolerating_reboot(odrv, api, 'erase_configuration'):
        call_tolerating_reboot(odrv, api, 'reboot')
    odrv = wait_for_drive(api, serial)
    print('  erased; drive reports node ID {} (firmware default)'.format(read_node_id(odrv)))

    # 3. Restore the target config with this drive's own node ID patched in, so
    #    the save below never commits the wrong one.
    patched = patch_node_id(target_nested, node_id)
    print('  restoring config with node_id={}...'.format(node_id))
    result.restore_errors = list(api.restore_config(odrv, patched) or [])
    for line in result.restore_errors:
        print('    ! {}'.format(line))
    if result.restore_errors and not ignore_restore_errors:
        result.status = 'restore errors'
        raise SystemExit(
            '\n{} property write(s) failed on node {}. Stopping before the next '
            'drive — this usually means a firmware/snapshot mismatch, which '
            'would repeat on all six.\nThe drive is left with the values that '
            'did apply, UNSAVED; power-cycle it to get the erased defaults '
            'back, or restore {}.\nPass --ignore-restore-errors if these '
            'warnings are expected.'.format(
                len(result.restore_errors), node_id,
                os.path.relpath(result.backup_path, _PROJECT_ROOT))
        )

    # 4. Commit to NVM, then reboot — so step 5 reads NVM and not RAM.
    print('  saving configuration...')
    if not call_tolerating_reboot(odrv, api, 'save_configuration'):
        call_tolerating_reboot(odrv, api, 'reboot')
    odrv = wait_for_drive(api, serial)

    # 5. Verify against what we meant to write.
    result.node_id_after = read_node_id(odrv)
    result.verify_rows = diff_flat(api.backup_config(odrv), flatten_config(patched))
    result.status = 'done'

    if result.node_id_after != node_id:
        print('  ! node ID reads {} after reboot, expected {}'.format(
            result.node_id_after, node_id))
    if result.verify_rows:
        print('  ! {} property(ies) do not match the target after reboot:'.format(
            len(result.verify_rows)))
        for path, actual, want in result.verify_rows[:20]:
            print('      {}: drive={!r} target={!r}'.format(path, actual, want))
        if len(result.verify_rows) > 20:
            print('      ... and {} more'.format(len(result.verify_rows) - 20))
    if result.ok:
        print('  verified: node ID {} and all {} properties match NVM'.format(
            node_id, len(flatten_config(patched))))
    return result


