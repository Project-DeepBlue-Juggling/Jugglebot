def flatten_config(nested: Dict[str, Any], prefix: str = '') -> Dict[str, Any]:
    """Flatten a nested config dict to ``{'a.b.c': value}``.

    Accepts an already-flat dict unchanged, so it works on both shapes of
    backup file: this odrivetool writes flat, older ones wrote nested.
    """
    flat: Dict[str, Any] = {}
    for key, value in nested.items():
        path = '{}.{}'.format(prefix, key) if prefix else key
        if isinstance(value, dict):
            flat.update(flatten_config(value, path))
        else:
            flat[path] = value
    return flat


def set_config_value(config: Dict[str, Any], path: str, value: Any) -> Dict[str, Any]:
    """Return a copy of ``config`` with ``path`` set to ``value``.

    Handles both file shapes: this odrivetool writes flat backups (the whole
    dotted path is one key), older ones and the repo snapshot were nested.

    Raises ``KeyError`` if the path is absent, which means the file is not the
    ODrive config backup it was taken for — cheaper to catch here than after
    six drives have been erased.
    """
    patched = copy.deepcopy(config)

    if path in patched:  # flat shape
        patched[path] = value
        return patched

    parts = path.split('.')
    node = patched
    for part in parts[:-1]:
        child = node.get(part)
        if not isinstance(child, dict):
            raise KeyError(
                'target config has no {} — is this an ODrive config backup?'.format(path))
        node = child
    if parts[-1] not in node:
        raise KeyError(
            'target config has no {} — is this an ODrive config backup?'.format(path))
    node[parts[-1]] = value
    return patched


def patch_node_id(config: Dict[str, Any], node_id: int) -> Dict[str, Any]:
    """Return a copy of ``config`` carrying ``node_id`` instead of the snapshot's."""
    return set_config_value(config, NODE_ID_PATH, int(node_id))


def calibration_travel_mm(scan_distance_rev: float, node_id: int) -> float:
    """Leg travel commanded by an open-loop calibration scan of that many revs."""
    if not 0 <= node_id < len(MM_PER_REV):
        raise IndexError('no spool geometry for node ID {}'.format(node_id))
    return scan_distance_rev * MM_PER_REV[node_id]


def check_calibration_travel(
    scan_distance_rev: float,
    node_ids: Sequence[int],
    stroke_mm: float = LEG_STROKE_MM,
) -> List[str]:
    """Problems if the calibration scan would drive a leg past its stroke.

    ``ENCODER_OFFSET_CALIBRATION`` scans open-loop for ``calib_scan_distance``
    revolutions — it has no idea the axis is a spool on a 280 mm actuator, and
    nothing in the ODrive stops it at the end of travel.

    Necessary but not sufficient: this compares against the WHOLE stroke, while
    the leg needs that much travel remaining *in the scan direction*. The scan
    runs the full distance one way and then back (ODrive 0.5.6
    ``Encoder::run_offset_calibration``: the forward loop's only exit is
    ``total_distance >= calib_scan_distance``, with no index check), so the
    excursion is one-directional from wherever the leg happens to be sitting.
    """
    problems: List[str] = []
    for node_id in sorted(set(node_ids)):
        travel = calibration_travel_mm(scan_distance_rev, node_id)
        if travel > stroke_mm:
            problems.append(
                'node {}: a {:.1f} rev scan is {:.0f} mm of leg travel against a '
                '{:.0f} mm stroke ({:.1f}x)'.format(
                    node_id, scan_distance_rev, travel, stroke_mm, travel / stroke_mm))
    return problems


def describe_calibration_motion(
    scan_distance_rev: float,
    scan_vel_rev_s: float,
    node_ids: Sequence[int],
) -> List[str]:
    """Human-readable summary of what the calibration will physically do."""
    lines = [
        'FULL_CALIBRATION_SEQUENCE will be run on node(s) {}, one at a time.'.format(
            sorted(set(node_ids))),
        'It MOVES THE MOTOR: motor calibration (a twitch), index search (bounded',
        'by the index pulse, under 1 rev — this robot has measured ~0.035 rev),',
        'then an open-loop encoder-offset scan of {:.1f} rev at {:.1f} rev/s.'.format(
            scan_distance_rev, scan_vel_rev_s),
        'The offset scan does NOT stop at the index: it runs the full distance one',
        'way and back, so the excursion below is one-directional from wherever the',
        'leg is sitting. Position each leg with that much travel free.',
    ]
    for node_id in sorted(set(node_ids)):
        lines.append('  node {}: {:.0f} mm of leg travel at {:.0f} mm/s (stroke {:.0f} mm)'.format(
            node_id,
            calibration_travel_mm(scan_distance_rev, node_id),
            scan_vel_rev_s * MM_PER_REV[node_id],
            LEG_STROKE_MM))
    return lines


def values_equal(left: Any, right: Any) -> bool:
    """Compare two config values, treating NaN as equal to NaN.

    Every value here has made a float32 round trip through the same codec, so
    an exact comparison is right — a tolerance would hide a failed write.
    """
    if isinstance(left, float) and isinstance(right, float):
        if math.isnan(left) and math.isnan(right):
            return True
    try:
        return bool(left == right)
    except Exception:
        return False


def diff_flat(actual: Dict[str, Any], expected: Dict[str, Any]) -> List[Tuple[str, Any, Any]]:
    """Rows of ``(path, actual, expected)`` where the drive disagrees.

    Iterates the *expected* keys only: the drive legitimately exposes config
    properties the snapshot does not carry, and those are not a mismatch.
    """
    rows: List[Tuple[str, Any, Any]] = []
    for path in sorted(expected):
        want = expected[path]
        if path not in actual:
            rows.append((path, '<absent on drive>', want))
        elif not values_equal(actual[path], want):
            rows.append((path, actual[path], want))
    return rows


def check_target_is_leg_config(flat_target: Dict[str, Any]) -> List[str]:
    """Refuse a target file that is plainly not a leg config.

    The hand snapshot commutates off ONBOARD_ENCODER0; flashing it to a leg
    would leave the leg with no usable commutation source.
    """
    problems: List[str] = []
    encoder = flat_target.get(COMMUTATION_ENCODER_PATH)
    if encoder is None:
        problems.append('{} missing — not an ODrive Pro axis config'.format(COMMUTATION_ENCODER_PATH))
    elif encoder != INC_ENCODER0:
        problems.append(
            '{} is {} (expected {} = INC_ENCODER0). This looks like the HAND '
            'config, not a leg config.'.format(COMMUTATION_ENCODER_PATH, encoder, INC_ENCODER0)
        )
    return problems


def validate_fleet(
    node_by_serial: Dict[str, int],
    leg_ids: Sequence[int] = LEG_NODE_IDS,
    protected_ids: Sequence[int] = PROTECTED_NODE_IDS,
) -> Tuple[List[str], List[str]]:
    """Check a discovered fleet. Returns ``(errors, warnings)``.

    Errors are conditions under which the serial -> node-ID association cannot
    be trusted, and so nothing may be erased.
    """
    errors: List[str] = []
    warnings: List[str] = []
    ids = list(node_by_serial.values())

    duplicates = sorted({i for i in ids if ids.count(i) > 1})
    if duplicates:
        errors.append(
            'node IDs {} reported by more than one drive — cannot tell which leg is '
            'which. If a previous run was interrupted mid-erase, rerun with '
            '--map <fleet_map.json> to resolve node IDs by USB serial.'.format(duplicates)
        )

    missing_legs = [i for i in leg_ids if i not in ids]
    if missing_legs:
        errors.append('leg node IDs {} not found on USB'.format(missing_legs))

    known = set(leg_ids) | set(protected_ids)
    unexpected = sorted({i for i in ids if i not in known})
    if unexpected:
        errors.append(
            'unrecognised node IDs {} on USB — not in the leg set {} or the '
            'protected set {}. Refusing to guess.'.format(
                unexpected, list(leg_ids), list(protected_ids))
        )

    missing_protected = [i for i in protected_ids if i not in ids]
    if missing_protected:
        warnings.append(
            'protected node IDs {} not found on USB (hand drive unplugged or '
            'unpowered?) — nothing to protect, continuing'.format(missing_protected))

    return errors, warnings


def find_conflicting_processes(cmdlines: Sequence[str]) -> List[Tuple[str, str]]:
    """Match running command lines against ``CONFLICTING_PATTERNS``."""
    self_name = os.path.basename(__file__)
    hits: List[Tuple[str, str]] = []
    for cmd in cmdlines:
        if self_name in cmd:
            continue  # this process, or a sibling invocation of it
        for pattern in CONFLICTING_PATTERNS:
            if pattern in cmd:
                hits.append((pattern, cmd))
                break
    return hits


def read_proc_cmdlines() -> List[str]:
    """Command lines of every visible process. Best effort — empty on failure."""
    cmdlines: List[str] = []
    try:
        pids = [entry for entry in os.listdir('/proc') if entry.isdigit()]
    except OSError:
        return cmdlines
    for pid in pids:
        try:
            with open('/proc/{}/cmdline'.format(pid), 'rb') as handle:
                raw = handle.read()
        except OSError:
            continue  # process exited, or not ours to read
        if raw:
            cmdlines.append(raw.replace(b'\0', b' ').decode('utf-8', 'replace').strip())
    return cmdlines


