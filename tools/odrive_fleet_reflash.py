def flatten_config(nested: Dict[str, Any], prefix: str = '') -> Dict[str, Any]:
    """Flatten a nested config dict to ``{'a.b.c': value}``.

    Accepts an already-flat dict unchanged, so it works on both shapes of
    backup file: this odrivetool writes flat, older ones wrote nested.
    """
    flat: Dict[str, Any] = {}
    for key, value in nested.items():
        path = '{}.{}'.format(prefix, key) if prefix else key
        if isinstance(value, dict):
            flat.update(flatten_config(value, path))
        else:
            flat[path] = value
    return flat


def patch_node_id(config: Dict[str, Any], node_id: int) -> Dict[str, Any]:
    """Return a copy of ``config`` with ``NODE_ID_PATH`` set to ``node_id``.

    Raises ``KeyError`` if the path is absent — that means the file is not an
    ODrive config backup, and catching it here is cheaper than catching it
    after six drives have been erased.
    """
    patched = copy.deepcopy(config)
    parts = NODE_ID_PATH.split('.')

    # Flat-shaped file: the whole dotted path is a single key.
    if NODE_ID_PATH in patched:
        patched[NODE_ID_PATH] = int(node_id)
        return patched

    node = patched
    for part in parts[:-1]:
        child = node.get(part)
        if not isinstance(child, dict):
            raise KeyError(
                'target config has no {} — is this an ODrive config backup?'.format(NODE_ID_PATH)
            )
        node = child
    if parts[-1] not in node:
        raise KeyError(
            'target config has no {} — is this an ODrive config backup?'.format(NODE_ID_PATH)
        )
    node[parts[-1]] = int(node_id)
    return patched


def values_equal(left: Any, right: Any) -> bool:
    """Compare two config values, treating NaN as equal to NaN.

    Every value here has made a float32 round trip through the same codec, so
    an exact comparison is right — a tolerance would hide a failed write.
    """
    if isinstance(left, float) and isinstance(right, float):
        if math.isnan(left) and math.isnan(right):
            return True
    try:
        return bool(left == right)
    except Exception:
        return False


def diff_flat(actual: Dict[str, Any], expected: Dict[str, Any]) -> List[Tuple[str, Any, Any]]:
    """Rows of ``(path, actual, expected)`` where the drive disagrees.

    Iterates the *expected* keys only: the drive legitimately exposes config
    properties the snapshot does not carry, and those are not a mismatch.
    """
    rows: List[Tuple[str, Any, Any]] = []
    for path in sorted(expected):
        want = expected[path]
        if path not in actual:
            rows.append((path, '<absent on drive>', want))
        elif not values_equal(actual[path], want):
            rows.append((path, actual[path], want))
    return rows


def check_target_is_leg_config(flat_target: Dict[str, Any]) -> List[str]:
    """Refuse a target file that is plainly not a leg config.

    The hand snapshot commutates off ONBOARD_ENCODER0; flashing it to a leg
    would leave the leg with no usable commutation source.
    """
    problems: List[str] = []
    encoder = flat_target.get(COMMUTATION_ENCODER_PATH)
    if encoder is None:
        problems.append('{} missing — not an ODrive Pro axis config'.format(COMMUTATION_ENCODER_PATH))
    elif encoder != INC_ENCODER0:
        problems.append(
            '{} is {} (expected {} = INC_ENCODER0). This looks like the HAND '
            'config, not a leg config.'.format(COMMUTATION_ENCODER_PATH, encoder, INC_ENCODER0)
        )
    return problems


def validate_fleet(
    node_by_serial: Dict[str, int],
    leg_ids: Sequence[int] = LEG_NODE_IDS,
    protected_ids: Sequence[int] = PROTECTED_NODE_IDS,
) -> Tuple[List[str], List[str]]:
    """Check a discovered fleet. Returns ``(errors, warnings)``.

    Errors are conditions under which the serial -> node-ID association cannot
    be trusted, and so nothing may be erased.
    """
    errors: List[str] = []
    warnings: List[str] = []
    ids = list(node_by_serial.values())

    duplicates = sorted({i for i in ids if ids.count(i) > 1})
    if duplicates:
        errors.append(
            'node IDs {} reported by more than one drive — cannot tell which leg is '
            'which. If a previous run was interrupted mid-erase, rerun with '
            '--map <fleet_map.json> to resolve node IDs by USB serial.'.format(duplicates)
        )

    missing_legs = [i for i in leg_ids if i not in ids]
    if missing_legs:
        errors.append('leg node IDs {} not found on USB'.format(missing_legs))

    known = set(leg_ids) | set(protected_ids)
    unexpected = sorted({i for i in ids if i not in known})
    if unexpected:
        errors.append(
            'unrecognised node IDs {} on USB — not in the leg set {} or the '
            'protected set {}. Refusing to guess.'.format(
                unexpected, list(leg_ids), list(protected_ids))
        )

    missing_protected = [i for i in protected_ids if i not in ids]
    if missing_protected:
        warnings.append(
            'protected node IDs {} not found on USB (hand drive unplugged or '
            'unpowered?) — nothing to protect, continuing'.format(missing_protected))

    return errors, warnings


def find_conflicting_processes(cmdlines: Sequence[str]) -> List[Tuple[str, str]]:
    """Match running command lines against ``CONFLICTING_PATTERNS``."""
    self_name = os.path.basename(__file__)
    hits: List[Tuple[str, str]] = []
    for cmd in cmdlines:
        if self_name in cmd:
            continue  # this process, or a sibling invocation of it
        for pattern in CONFLICTING_PATTERNS:
            if pattern in cmd:
                hits.append((pattern, cmd))
                break
    return hits


def read_proc_cmdlines() -> List[str]:
    """Command lines of every visible process. Best effort — empty on failure."""
    cmdlines: List[str] = []
    try:
        pids = [entry for entry in os.listdir('/proc') if entry.isdigit()]
    except OSError:
        return cmdlines
    for pid in pids:
        try:
            with open('/proc/{}/cmdline'.format(pid), 'rb') as handle:
                raw = handle.read()
        except OSError:
            continue  # process exited, or not ours to read
        if raw:
            cmdlines.append(raw.replace(b'\0', b' ').decode('utf-8', 'replace').strip())
    return cmdlines


