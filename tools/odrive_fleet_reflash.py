#: Node IDs this script will erase and reflash. From the generated config so the
#: fleet definition has one home (``config/protocol_config.yaml``).
LEG_NODE_IDS: Tuple[int, ...] = tuple(proto.NODE_ID_LEGS)

#: Node IDs that are discovered and recorded but never written to.
PROTECTED_NODE_IDS: Tuple[int, ...] = (proto.NODE_ID_JUGGLEBOT_HAND,)

DEFAULT_TARGET_CONFIG = os.path.join(
    _PROJECT_ROOT, 'config', 'ODrive config Files', 'odrive_pro_leg_config.json'
)
DEFAULT_BACKUP_ROOT = os.path.join(_PROJECT_ROOT, 'temp', 'odrive_configs')

NODE_ID_PATH = 'axis0.config.can.node_id'
COMMUTATION_ENCODER_PATH = 'axis0.config.commutation_encoder'

#: EncoderId.INC_ENCODER0 — what a leg commutates off. The hand config says 13
#: (ONBOARD_ENCODER0), which is how this script recognises the wrong file.
INC_ENCODER0 = 1

#: Discovery / reboot timings. A Pro takes ~2 s to drop off USB and come back.
DISCOVERY_TIMEOUT_S = 30.0
REBOOT_SETTLE_S = 2.0
REBOOT_TIMEOUT_S = 30.0

#: Processes that must not be running: the first three command the drives over
#: CAN, the last two hold an exclusive USB claim on them.
CONFLICTING_PATTERNS = (
    'teensy_bridge_node',
    'jugglebot_launch',
    'trajectory_node',
    'odrivetool',
    'odrive_gui',
)


