class OdriveApi:
    """The bits of the odrive package this script uses.

    Imported lazily so the module stays importable (and unit-testable) on a box
    without the odrive package or without hardware attached.
    """

    def __init__(self) -> None:
        try:
            import odrive
            from odrive.legacy_config import backup_config, restore_config
            from odrive.libodrive import DeviceLostException
        except ImportError as exc:
            raise SystemExit(
                'could not import the odrive package ({}).\n'
                'Activate the project venv first:\n'
                '    source ~/Desktop/PDJ_venv/venv/bin/activate'.format(exc)
            )
        self.odrive = odrive
        self.backup_config = backup_config
        self.restore_config = restore_config
        self.DeviceLostException = DeviceLostException


def usb_serial(odrv: Any) -> str:
    """The USB serial string, which is what ``find_sync`` matches on.

    Deliberately ``_dev.serial_number`` and not ``odrv.serial_number``: the
    latter is the firmware's uint64 property, while discovery keys off the USB
    descriptor string in ``RuntimeDevice.serial_number``.
    """
    return odrv._dev.serial_number


def read_node_id(odrv: Any) -> int:
    return int(odrv.axis0.config.can.node_id)


def read_fw_version(odrv: Any) -> Optional[str]:
    try:
        return '{}.{}.{}'.format(
            odrv.fw_version_major, odrv.fw_version_minor, odrv.fw_version_revision
        )
    except Exception:
        return None


def is_alive(odrv: Any) -> bool:
    """True if the handle still answers a read."""
    try:
        read_node_id(odrv)
        return True
    except Exception:
        return False


def discover(api: OdriveApi, count: int, timeout: float) -> List[Any]:
    """Block until ``count`` drives are connected, then return them."""
    print('Waiting for {} ODrives on USB (timeout {:.0f} s)...'.format(count, timeout))
    try:
        drives = api.odrive.find_sync(count=count, timeout=timeout)
    except TimeoutError:
        raise SystemExit(
            'timed out waiting for {} ODrives. Check power and USB, or pass '
            '--expect <n> if fewer are attached.'.format(count)
        )
    return list(drives)


def call_tolerating_reboot(odrv: Any, api: OdriveApi, name: str) -> bool:
    """Call a function that is expected to reboot the drive.

    Returns True if the drive went away (the call landed and the reboot began).
    """
    if not hasattr(odrv, name):
        # Never silently skip the erase: "reflashed without erasing" is a
        # different operation from the one the caller asked for.
        raise SystemExit(
            'this firmware exposes no {}() — refusing to continue, since the '
            'erase step cannot be verified.'.format(name))
    try:
        getattr(odrv, name)()
    except api.DeviceLostException:
        return True
    except Exception as exc:
        # Not necessarily fatal: some transports surface the lost connection as
        # a generic error on the reboot ack path. Probe rather than assume.
        print('      note: {}() raised {}: {}'.format(name, type(exc).__name__, exc))
    return not is_alive(odrv)


def wait_for_drive(api: OdriveApi, serial: str, timeout: float = REBOOT_TIMEOUT_S) -> Any:
    """Wait for ``serial`` to reappear after a reboot and answer a read."""
    time.sleep(REBOOT_SETTLE_S)  # let the old handle be reaped before re-asking
    deadline = time.time() + timeout
    while True:
        remaining = deadline - time.time()
        if remaining <= 0:
            raise SystemExit(
                'ODrive {} did not come back within {:.0f} s of a reboot. Its '
                'config may be half-written — restore from the backup in the '
                'backup directory before using it.'.format(serial, timeout)
            )
        try:
            odrv = api.odrive.find_sync(serial_number=serial, timeout=remaining)
        except TimeoutError:
            continue
        if is_alive(odrv):
            return odrv
        time.sleep(0.5)


