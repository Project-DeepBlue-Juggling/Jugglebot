#!/usr/bin/env python3
"""Fleet-wide leg-ODrive config reset — back up, erase, reflash, restore node IDs.

Automates, across all six leg drives in one pass, the manual ``odrivetool``
procedure this project has used one drive at a time: ``erase_configuration()``
in the shell, then ``odrivetool restore-config``, then re-set
``axis0.config.can.node_id`` and save.

Standing quirk this exists to service: this machine's ODrives occasionally need
a config reset (cause unknown — one cured the 2026-08-10 leg-0
``SPINOUT_DETECTED``). A bare reset reverts every tuned value, so the reset is
only half the job — the config JSON has to go back on afterwards.

What it does, per drive
-----------------------
1. **Records** the USB-serial -> CAN-node-ID mapping for every drive on the bus
   and writes it to ``fleet_map.json`` *before* anything is erased. That file is
   the recovery key: an erased drive reports the firmware-default node ID, so
   the association is unrecoverable from the hardware alone.
2. **Backs up** the drive's current config (byte-for-byte what ``odrivetool
   backup-config`` writes) next to the map.
3. **Erases** with ``erase_configuration()``, then reboots so RAM holds defaults
   too, not just NVM.
4. **Reflashes** the target config with that drive's own node ID already patched
   in, then ``save_configuration()``.
5. **Verifies** — after a forced reboot, so the read comes from NVM — that every
   property in the target file reads back, and that the node ID is right.

Two design points worth knowing:

*The node ID is patched into the restore dict rather than fixed up afterwards*,
so no ``save_configuration()`` ever commits the wrong node ID to NVM. Six drives
persistently answering as node 0 on a shared bus is worth one less reboot.

*The verify pass forces a reboot first.* After the restore, the correct values
are already in RAM — so a verify that reads a live drive cannot distinguish a
successful ``save_configuration()`` from one that silently refused (an armed
axis, for instance). Only a post-reboot read proves NVM took it.

The hand drive (CAN node 6, ``NODE_ID_JUGGLEBOT_HAND``) is discovered, recorded,
and then left strictly alone — it runs a different config file
(``odrive_pro_hand_config.json``: ONBOARD_ENCODER0, not INC_ENCODER0).

Per-motor calibration values — ``commutation_mapper.config.index_offset``,
``motor.phase_resistance``/``phase_inductance`` — are flashed **verbatim from
the snapshot and are NOT preserved per drive** (owner's call, 2026-08-12: they
are regenerated by the next index search). Consequence: **home every leg before
arming it.** Until index search has run, each leg carries the snapshot drive's
commutation offset.

Preconditions
-------------
* All seven drives powered and on USB.
* The ROS stack **stopped**. A live ``teensy_bridge_node`` streams setpoints to
  CAN node IDs 0-5 at 500 Hz, and freshly-erased drives all answer as one node.
  The script refuses to start if it sees one (``--force`` overrides). An open
  ``odrivetool`` shell or ODrive GUI is the same problem for a different reason:
  it holds an exclusive USB claim on the drives.
* Every axis idle — ``save_configuration()`` refuses on an armed axis.

Usage
-----
    source ~/Desktop/PDJ_venv/venv/bin/activate

    # read-only: discover, record the map, back everything up, diff vs target
    python tools/odrive_fleet_reflash.py --dry-run

    # the real thing — all six legs, unattended
    python tools/odrive_fleet_reflash.py

    # one drive only; or resume a partial run off the recorded map
    python tools/odrive_fleet_reflash.py --only 3
    python tools/odrive_fleet_reflash.py --map temp/odrive_configs/<ts>/fleet_map.json

``--map`` is the fix for the one state this script can otherwise not reason
about: a run that died between erase and restore leaves a drive at the default
node ID, which collides with leg 0 and makes the live node-ID read ambiguous.
The map resolves node IDs by USB serial instead, so a rerun just works.

Recovery: every drive's pre-erase config is in the backup directory and is
restorable with ``odrivetool restore-config <backup.json>`` — though ``--map``
plus a rerun is usually faster, since the backup carries the old node ID too.
"""

