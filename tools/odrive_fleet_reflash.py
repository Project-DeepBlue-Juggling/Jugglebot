class DriveResult:
    def __init__(self, node_id: int, serial: str) -> None:
        self.node_id = node_id
        self.serial = serial
        self.backup_path: Optional[str] = None
        self.restore_errors: List[str] = []
        self.verify_rows: List[Tuple[str, Any, Any]] = []
        self.node_id_after: Optional[int] = None
        self.calibration: Optional[CalibrationOutcome] = None
        self.calib_changes: List[Tuple[str, Any, Any]] = []
        self.unexpected_calib_changes: List[Tuple[str, Any, Any]] = []
        self.status = 'not started'

    @property
    def ok(self) -> bool:
        calibration_ok = self.calibration is None or self.calibration.ok
        return (
            self.status == 'done'
            and not self.restore_errors
            and not self.verify_rows
            and self.node_id_after == self.node_id
            and calibration_ok
        )


def write_backup(api: OdriveApi, odrv: Any, path: str) -> Dict[str, Any]:
    """Read the drive's config and write it in ``odrivetool backup-config`` form."""
    config = api.backup_config(odrv)
    with open(path, 'w') as handle:
        json.dump(config, handle, indent=2)
    return config


def process_drive(
    api: OdriveApi,
    odrv: Any,
    node_id: int,
    target_nested: Dict[str, Any],
    backup_dir: str,
    ignore_restore_errors: bool,
    calibrate: bool = False,
    calib_timeout: float = CALIB_TIMEOUT_S,
) -> DriveResult:
    """Back up, erase, reflash, verify, then optionally calibrate one drive."""
    serial = usb_serial(odrv)
    result = DriveResult(node_id, serial)
    print('\n--- node {} (USB {}) -----------------------------------'.format(node_id, serial))

    # 1. Back up before anything is destroyed.
    result.backup_path = os.path.join(
        backup_dir, 'pre_erase_node{}_{}.json'.format(node_id, serial))
    write_backup(api, odrv, result.backup_path)
    print('  backed up  -> {}'.format(os.path.relpath(result.backup_path, _PROJECT_ROOT)))

    # 2. Erase NVM, then reboot so RAM holds defaults too.
    print('  erasing configuration...')
    if not call_tolerating_reboot(odrv, api, 'erase_configuration'):
        call_tolerating_reboot(odrv, api, 'reboot')
    odrv = wait_for_drive(api, serial)
    print('  erased; drive reports node ID {} (firmware default)'.format(read_node_id(odrv)))

    # 3. Restore the target config with this drive's own node ID patched in, so
    #    the save below never commits the wrong one.
    patched = patch_node_id(target_nested, node_id)
    print('  restoring config with node_id={}...'.format(node_id))
    result.restore_errors = list(api.restore_config(odrv, patched) or [])
    for line in result.restore_errors:
        print('    ! {}'.format(line))
    if result.restore_errors and not ignore_restore_errors:
        result.status = 'restore errors'
        raise SystemExit(
            '\n{} property write(s) failed on node {}. Stopping before the next '
            'drive — this usually means a firmware/snapshot mismatch, which '
            'would repeat on all six.\nThe drive is left with the values that '
            'did apply, UNSAVED; power-cycle it to get the erased defaults '
            'back, or restore {}.\nPass --ignore-restore-errors if these '
            'warnings are expected.'.format(
                len(result.restore_errors), node_id,
                os.path.relpath(result.backup_path, _PROJECT_ROOT))
        )

    # 4. Commit to NVM, then reboot — so step 5 reads NVM and not RAM.
    print('  saving configuration...')
    if not call_tolerating_reboot(odrv, api, 'save_configuration'):
        call_tolerating_reboot(odrv, api, 'reboot')
    odrv = wait_for_drive(api, serial)

    # 5. Verify against what we meant to write. Deliberately BEFORE calibration:
    #    the calibration is about to spin the motor using these very values
    #    (calib_scan_vel, calibration_current, the encoder setup), so proving
    #    they are what NVM holds is worth doing while the axis is still still.
    result.node_id_after = read_node_id(odrv)
    flat_patched = flatten_config(patched)
    result.verify_rows = diff_flat(api.backup_config(odrv), flat_patched)
    result.status = 'done'

    if result.node_id_after != node_id:
        print('  ! node ID reads {} after reboot, expected {}'.format(
            result.node_id_after, node_id))
    if result.verify_rows:
        print('  ! {} property(ies) do not match the target after reboot:'.format(
            len(result.verify_rows)))
        for path, actual, want in result.verify_rows[:20]:
            print('      {}: drive={!r} target={!r}'.format(path, actual, want))
        if len(result.verify_rows) > 20:
            print('      ... and {} more'.format(len(result.verify_rows) - 20))
    if not result.verify_rows and result.node_id_after == node_id:
        print('  verified: node ID {} and all {} properties match NVM'.format(
            node_id, len(flat_patched)))

    if not calibrate:
        return result

    # 6. Calibrate. Snapshot first so the report of what calibration wrote is
    #    measured rather than assumed.
    pre_calib = api.backup_config(odrv)
    print('  running FULL_CALIBRATION_SEQUENCE — THE MOTOR WILL MOVE...')
    result.calibration = run_full_calibration(api, odrv, calib_timeout)
    print('  calibration: {}'.format(result.calibration))
    if result.calibration.active_errors or result.calibration.disarm_reason:
        print('    active_errors : {}'.format(api.error_name(result.calibration.active_errors)))
        print('    disarm_reason : {}'.format(api.error_name(result.calibration.disarm_reason)))

    if not result.calibration.ok:
        raise SystemExit(
            '\ncalibration FAILED on node {} ({}). Stopping before the next '
            'drive.\nThis leg now holds the flashed config in NVM — including '
            'the snapshot\'s commutation offset, marked valid — but its own '
            'calibration did NOT run. DO NOT ARM IT until calibration '
            'succeeds.\nCheck that the leg was free to move {:.0f} mm before '
            'retrying: --only {} reruns just this drive.'.format(
                node_id, result.calibration,
                calibration_travel_mm(
                    float(flat_patched.get(CALIB_SCAN_DISTANCE_PATH, 0.0)), node_id),
                node_id))

    # 7. One last save, so the freshly measured values survive a power cycle,
    #    then reboot and re-read — same reasoning as step 4/5.
    print('  saving calibration...')
    if not call_tolerating_reboot(odrv, api, 'save_configuration'):
        call_tolerating_reboot(odrv, api, 'reboot')
    odrv = wait_for_drive(api, serial)

    post_calib = api.backup_config(odrv)
    result.node_id_after = read_node_id(odrv)
    # What calibration actually changed, measured: (path, before, after).
    result.calib_changes = diff_flat(pre_calib, post_calib)
    result.unexpected_calib_changes = [
        row for row in result.calib_changes if row[0] not in CALIBRATION_OWNED_PATHS]
    # Re-verify the config, minus what calibration is supposed to own.
    result.verify_rows = [
        row for row in diff_flat(post_calib, flat_patched)
        if row[0] not in CALIBRATION_OWNED_PATHS]

    if result.calib_changes:
        print('  calibration wrote {} property(ies):'.format(len(result.calib_changes)))
        for path, before, after in result.calib_changes:
            marker = '   ' if path in CALIBRATION_OWNED_PATHS else ' ? '
            print('    {}{}: {!r} -> {!r}'.format(marker, path, before, after))
    else:
        print('  ! calibration reported success but changed no stored property')
    if result.unexpected_calib_changes:
        print('  ! {} of those are outside the expected calibration set (marked ?)'.format(
            len(result.unexpected_calib_changes)))
    if result.verify_rows:
        print('  ! {} property(ies) still do not match the target:'.format(
            len(result.verify_rows)))
        for path, actual, want in result.verify_rows[:20]:
            print('      {}: drive={!r} target={!r}'.format(path, actual, want))
    if result.ok:
        print('  verified after calibration: node ID {}, config matches, '
              'calibration SUCCESS'.format(node_id))
    return result


