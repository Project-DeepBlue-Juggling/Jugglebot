"""Platform IMU mount calibration: the file, its validation and the rotation into the Platform frame.

Standard library only (json, math, os, array), Python 3.8: ``ros_ws/gui/imu_api.py`` loads this file by path
(without importing the ``teensy_link`` package, whose ``__init__`` pulls the link client), and
``platform_imu_capture`` applies it to numpy arrays. The artefact is ``config/platform_imu_mount.json``
(measured at the Sitting of 2026-11-22, Rung P5; JSON because the GUI server is stdlib-only and cannot read
YAML). It is NOT generated by ``config/generate_config.py``.

What :func:`rotate_xyz` does and does not do. It multiplies each (x, y, z) triple by ``R_PI`` (IMU frame to
Platform frame, ``v_platform = R_PI @ v_imu``) and nothing else: **no gravity subtraction, no gyro bias, no
lever arm** (the Platform is a rigid body, so the lever arm matters only for linear acceleration during rotation,
and the CAD value is not measured). The accelerometer reads specific force, so a still, Level Platform reads
about (0, 0, +1 g) after rotation. Raw data on disk stays in the IMU frame.

Absent file: :func:`load_mount` returns ``None`` (calibration not done). A present but malformed file raises
:class:`MountCalError`: a half-trusted rotation is worse than none.
"""

from __future__ import annotations

import json
import math
import os
from typing import Any, Dict, List, Optional, Sequence

SCHEMA_VERSION = 1
ORTHO_TOL = 1e-6          # max |R R^T - I| entry and |det - 1|
DEFAULT_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                            "config", "platform_imu_mount.json")


class MountCalError(ValueError):
    """The mount calibration file exists but is unusable."""


class MountCalibration:
    """A validated calibration: ``matrix`` (3 rows of 3 floats), ``date``, the raw ``doc`` and ``path``."""

    def __init__(self, matrix: List[List[float]], date: str, doc: Dict[str, Any], path: str) -> None:
        self.matrix = matrix
        self.date = date
        self.doc = doc
        self.path = path

    @property
    def gyro_bias_dps(self) -> List[float]:
        return list(self.doc["gyro_bias"]["values_dps_imu_frame"])


def _is_num(x: Any) -> bool:
    return isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x)


def validate_matrix(m: Any) -> List[List[float]]:
    """3x3 finite numbers, orthonormal within ``ORTHO_TOL``, determinant +1; else :class:`MountCalError`."""
    if not (isinstance(m, list) and len(m) == 3 and all(isinstance(r, list) and len(r) == 3 for r in m)):
        raise MountCalError("rotation.matrix must be 3 rows of 3 numbers")
    if not all(_is_num(x) for r in m for x in r):
        raise MountCalError("rotation.matrix holds a non-finite or non-numeric entry")
    r = [[float(x) for x in row] for row in m]
    for i in range(3):
        for j in range(3):
            dot = sum(r[i][k] * r[j][k] for k in range(3))
            if abs(dot - (1.0 if i == j else 0.0)) > ORTHO_TOL:
                raise MountCalError("rotation.matrix is not orthonormal (R R^T entry [%d][%d] = %.3g)" % (i, j, dot))
    det = (r[0][0] * (r[1][1] * r[2][2] - r[1][2] * r[2][1])
           - r[0][1] * (r[1][0] * r[2][2] - r[1][2] * r[2][0])
           + r[0][2] * (r[1][0] * r[2][1] - r[1][1] * r[2][0]))
    if abs(det - 1.0) > ORTHO_TOL:
        raise MountCalError("rotation.matrix has determinant %.6g, not +1 (a reflection or a scaled matrix)" % det)
    return r


def parse_mount(doc: Any, path: str = "") -> MountCalibration:
    if not isinstance(doc, dict):
        raise MountCalError("calibration root must be an object")
    if doc.get("schema_version") != SCHEMA_VERSION:
        raise MountCalError("unsupported schema_version %r (this loader reads %d)" % (doc.get("schema_version"), SCHEMA_VERSION))
    rot = doc.get("rotation")
    if not isinstance(rot, dict):
        raise MountCalError("missing rotation block")
    matrix = validate_matrix(rot.get("matrix"))
    prov = doc.get("provenance")
    date = prov.get("date") if isinstance(prov, dict) else None
    if not isinstance(date, str) or not date:
        raise MountCalError("missing provenance.date")
    bias = (doc.get("gyro_bias") or {}).get("values_dps_imu_frame") if isinstance(doc.get("gyro_bias"), dict) else None
    if not (isinstance(bias, list) and len(bias) == 3 and all(_is_num(x) for x in bias)):
        raise MountCalError("gyro_bias.values_dps_imu_frame must be 3 numbers")
    return MountCalibration(matrix, date, doc, path)


def load_mount(path: Optional[str] = None) -> Optional[MountCalibration]:
    """The calibration at ``path`` (default ``config/platform_imu_mount.json``), ``None`` if the file is absent,
    :class:`MountCalError` if it is present and malformed (unreadable JSON included)."""
    path = path or DEFAULT_PATH
    try:
        with open(path, "r") as f:
            text = f.read()
    except FileNotFoundError:
        return None
    except OSError as exc:
        raise MountCalError("cannot read %s: %s" % (path, exc))
    try:
        doc = json.loads(text)
    except ValueError as exc:
        raise MountCalError("%s is not valid JSON: %s" % (path, exc))
    return parse_mount(doc, path)


def rotate_xyz(flat: Sequence[float], matrix: Sequence[Sequence[float]]):
    """Rotate a flat row-major sequence of (x, y, z) triples by ``matrix``; returns an ``array.array('f')``
    of the same length. Pure Python (the GUI path): strided slices and one comprehension per output axis,
    about 3x faster than a per-triple loop."""
    import array
    (a, b, c), (d, e, f), (g, h, i) = matrix
    n = len(flat) // 3
    fl = flat if isinstance(flat, array.array) else array.array("f", flat)
    xs, ys, zs = fl[0:3 * n:3], fl[1:3 * n:3], fl[2:3 * n:3]
    out = array.array("f", bytes(4 * 3 * n))
    out[0::3] = array.array("f", [a * x + b * y + c * z for x, y, z in zip(xs, ys, zs)])
    out[1::3] = array.array("f", [d * x + e * y + f * z for x, y, z in zip(xs, ys, zs)])
    out[2::3] = array.array("f", [g * x + h * y + i * z for x, y, z in zip(xs, ys, zs)])
    return out
