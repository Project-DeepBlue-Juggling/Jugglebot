"""Generate ``logbook/INDEX.md`` from logbook entry frontmatter.

One row per entry, built only from fields the entry already carries: Date =
``date``, Status = ``status``, Phase = ``phase``, Title = ``title`` (bold, capped
at :data:`TITLE_CAP` characters on a word boundary), Entry = a link to the file.
Newest first by date, ties by filename descending. Rows are never hand-edited:
``python -m mapkit gen`` rewrites them and ``tests/sim/test_logbook_index.py``
fails when the committed file is stale.

Historical entries are never rewritten, so irregular ones are read with
fallbacks rather than fixed: frontmatter that is not valid YAML is read line by
line (top-level ``key: value`` lines only); a missing date comes from the
filename prefix, a missing title from the first ``# `` heading, and a missing
status or phase renders as an em dash. :func:`fallback_counts` reports how many
entries needed each.
"""
from __future__ import annotations

import os
import re
from typing import Any, Dict, List, NamedTuple, Optional

from mapkit.frontmatter import FrontmatterError, split_frontmatter
from mapkit.gen_index import DASH, cell

LOGBOOK_DIR = "logbook"
INDEX_NAME = "INDEX.md"

#: Structural files in ``logbook/`` that are not entries (``sim/analysis/logbook_search.py``
#: ``_SKIP_FILES``). Subdirectories (``artifacts/``) are never scanned.
STRUCTURAL = frozenset({"INDEX.md", "README.md", "TEMPLATE.md"})

#: Longest rendered title, in characters before ``|`` escaping. The 2026-11-14 entry titles
#: had median 124, p90 256, p95 311, max 513; 280 leaves 93 % of them whole and cuts only
#: the long tail that reads as a summary rather than a title (the entry holds the rest).
TITLE_CAP = 280
ELLIPSIS = "…"

HEADER = (
    "# Engineering Logbook\n\n"
    "Structured record of investigations: symptom → diagnosis → fix → outcome.\n\n"
    "Browse with `/logbook`, create entries with `/investigate` or `/logbook --new <title>`.\n\n"
    "Generated by `python -m mapkit gen` from entry frontmatter -- do not hand-edit the rows; "
    "`tests/sim/test_logbook_index.py` fails if this file is stale.\n"
)
COLUMNS = ("Date", "Status", "Phase", "Title", "Entry")

_DATE_PREFIX = re.compile(r"^(\d{4}-\d{2}-\d{2})")
_TOP_KEY = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*):\s*(.*)$")
_HEADING = re.compile(r"^#\s+(.+?)\s*#*\s*$")


class Entry(NamedTuple):
    filename: str
    date: str
    status: Optional[str]
    phase: Optional[str]
    title: str
    fallbacks: tuple  # names of the fallbacks this entry needed, e.g. ("lenient-yaml",)


def _lenient_meta(text: str) -> Dict[str, Any]:
    """Top-level ``key: value`` scalars of a frontmatter block that is not valid YAML."""
    lines = text.split("\n")
    meta: Dict[str, Any] = {}
    for line in lines[1:]:
        if line.rstrip("\r") == "---":
            break
        m = _TOP_KEY.match(line.rstrip("\r"))
        if not m or not m.group(2):
            continue
        value = m.group(2).strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        meta[m.group(1)] = value
    return meta


def _text(value: Any) -> Optional[str]:
    if value is None:
        return None
    text = " ".join(str(value).split())
    return text or None


def read_entry(path: str) -> Entry:
    """One entry's row fields, with the fallbacks it needed."""
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    name = os.path.basename(path)
    used: List[str] = []
    try:
        meta, body = split_frontmatter(text)
    except FrontmatterError:
        meta, body = _lenient_meta(text), text
        used.append("lenient-yaml")
    date = _text(meta.get("date"))
    if date is None:
        m = _DATE_PREFIX.match(name)
        date = m.group(1) if m else ""
        used.append("date-from-filename")
    title = _text(meta.get("title"))
    if title is None:
        title = next((h.group(1) for h in map(_HEADING.match, body.split("\n")) if h),
                     name[:-3] if name.endswith(".md") else name)
        title = " ".join(title.split())
        used.append("title-from-heading")
    status, phase = _text(meta.get("status")), _text(meta.get("phase"))
    if status is None:
        used.append("no-status")
    if phase is None:
        used.append("no-phase")
    return Entry(name, date, status, phase, title, tuple(used))


def entry_files(repo_root: str) -> List[str]:
    """Entry filenames in ``logbook/`` (flat; structural files and subdirectories skipped)."""
    d = os.path.join(repo_root, LOGBOOK_DIR)
    return sorted(n for n in os.listdir(d)
                  if n.endswith(".md") and n not in STRUCTURAL
                  and os.path.isfile(os.path.join(d, n)))


def load_entries(repo_root: str) -> List[Entry]:
    d = os.path.join(repo_root, LOGBOOK_DIR)
    return [read_entry(os.path.join(d, n)) for n in entry_files(repo_root)]


def cap_title(title: str, cap: int = TITLE_CAP) -> str:
    """``title`` cut to at most ``cap`` characters on a word boundary, with an ellipsis."""
    if len(title) <= cap:
        return title
    cut = title[:cap - len(ELLIPSIS)]
    space = cut.rfind(" ")
    if space > cap // 2:
        cut = cut[:space]
    return cut.rstrip(" ,;:—-") + ELLIPSIS


def _row(cells: List[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def render(entries: List[Entry]) -> str:
    """Full text of ``logbook/INDEX.md`` (trailing newline included)."""
    ordered = sorted(entries, key=lambda e: (e.date, e.filename), reverse=True)
    lines = [_row(list(COLUMNS)), "|------|--------|-------|-------|-------|"]
    for e in ordered:
        stem = e.filename[:-3] if e.filename.endswith(".md") else e.filename
        lines.append(_row([cell(e.date), cell(e.status), cell(e.phase),
                           "**%s**" % cell(cap_title(e.title)),
                           "[%s](%s)" % (stem, e.filename)]))
    return HEADER + "\n" + "\n".join(lines) + "\n"


def fallback_counts(entries: List[Entry]) -> Dict[str, int]:
    out: Dict[str, int] = {}
    for e in entries:
        for f in e.fallbacks:
            out[f] = out.get(f, 0) + 1
    return out


def index_path(repo_root: str) -> str:
    return os.path.join(repo_root, LOGBOOK_DIR, INDEX_NAME)


def write_index(repo_root: str, check: bool = False) -> List[str]:
    """Rewrite ``logbook/INDEX.md`` if stale; return ``[path]`` if it changed, else ``[]``.

    A repo with no ``logbook/`` directory has no index to write. With ``check=True``
    nothing is written (the list is what *would* change).
    """
    if not os.path.isdir(os.path.join(repo_root, LOGBOOK_DIR)):
        return []
    text = render(load_entries(repo_root))
    path = index_path(repo_root)
    old: Optional[str] = None
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            old = fh.read()
    if old == text:
        return []
    if not check:
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    return [path]
