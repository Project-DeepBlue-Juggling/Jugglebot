"""Generate the three plan-board INDEX files from plan frontmatter.

Each file is a short static header plus one generated table. Rows are never
hand-edited: ``python -m mapkit gen`` rewrites them and
``tests/sim/test_plans_index.py`` fails when a committed file is stale.
"""
from __future__ import annotations

import os
from typing import Any, Dict, List, Optional

from mapkit.plans import BOARDS, Plan, load_plans

DASH = "—"

_GEN_LINE = ("Generated by `python -m mapkit gen` from plan frontmatter -- do not hand-edit "
             "the rows; `tests/sim/test_plans_index.py` fails if this file is stale.")

HEADERS = {
    "active": (
        "# Active plans\n\n"
        "The schedulable board: work that could be picked up now. Work that is deliberately "
        "not now is on `plans/parked/INDEX.md`; done or superseded work is on "
        "`plans/archived/INDEX.md`.\n\n" + _GEN_LINE + "\n"
    ),
    "parked": (
        "# Parked plans\n\n"
        "Deliberately not now: real, unfinished work whose named gate has not cleared. "
        "Every row says what would unpark it.\n\n" + _GEN_LINE + "\n"
    ),
    "archived": (
        "# Archived plans\n\n"
        "Completed or superseded plans, sorted by `archived:` date. A plan's filename never "
        "changes for its life; the date lives in `archived:` "
        "(`../../DOCUMENTATION_GUIDE.md` § 2.6).\n\n" + _GEN_LINE + "\n"
    ),
}

COLUMNS = {
    "active": ("Plan", "Status", "Last touched", "Scope"),
    "parked": ("Plan", "Parked", "Why parked", "What would unpark it"),
    "archived": ("Archived", "Plan", "Status", "Title"),
}


def cell(value: Any) -> str:
    """One table cell: newlines collapsed, ``|`` escaped, missing -> em dash."""
    if value is None:
        return DASH
    text = " ".join(str(value).split())
    if not text:
        return DASH
    return text.replace("|", "\\|")


def _link(plan: Plan) -> str:
    return "[%s](%s)" % (plan.filename, plan.filename)


def _is_reference(plan: Plan) -> bool:
    return plan.meta.get("kind") == "reference"


def _stable_desc(by_name: List[Plan], key: str) -> List[Plan]:
    dated = [p for p in by_name if p.meta.get(key)]
    undated = [p for p in by_name if not p.meta.get(key)]
    # Group by date descending; filename order (already ascending) kept inside a date.
    dates = sorted({str(p.meta[key]) for p in dated}, reverse=True)
    out: List[Plan] = []
    for d in dates:
        out.extend(p for p in dated if str(p.meta[key]) == d)
    return out + undated


def _row(cells: List[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def render_board(board: str, plans: List[Plan]) -> str:
    """Full text of the board's INDEX file (trailing newline included)."""
    if board not in HEADERS:
        raise ValueError("unknown board %r" % board)
    mine = [p for p in plans if p.board == board]
    lines = [_row(list(COLUMNS[board])), _row(["---"] * len(COLUMNS[board]))]
    if board == "active":
        ordered = _stable_desc(sorted((p for p in mine if not _is_reference(p)),
                                      key=lambda p: p.filename), "last_updated")
        refs = _stable_desc(sorted((p for p in mine if _is_reference(p)),
                                   key=lambda p: p.filename), "last_updated")
        for p in ordered + refs:
            status = "reference" if _is_reference(p) else p.meta.get("status")
            lines.append(_row([_link(p), cell(status), cell(p.meta.get("last_updated")),
                               cell(p.meta.get("scope"))]))
    elif board == "parked":
        for p in _stable_desc(sorted(mine, key=lambda p: p.filename), "parked"):
            lines.append(_row([_link(p), cell(p.meta.get("parked")),
                               cell(p.meta.get("parked_why")), cell(p.meta.get("unpark"))]))
    else:
        ordered = sorted(mine, key=lambda p: (str(p.meta.get("archived") or ""), p.filename))
        for p in ordered:
            lines.append(_row([cell(p.meta.get("archived")), _link(p),
                               cell(p.meta.get("status")), cell(p.meta.get("title"))]))
    return HEADERS[board] + "\n" + "\n".join(lines) + "\n"


def render_all(repo_root: str) -> Dict[str, str]:
    """Rendered text per board, keyed by board name."""
    plans = load_plans(repo_root)
    return {b: render_board(b, plans) for b in BOARDS}


def index_path(repo_root: str, board: str) -> str:
    return os.path.join(repo_root, "plans", board, "INDEX.md")


def write_indexes(repo_root: str, check: bool = False) -> List[str]:
    """Rewrite stale INDEX files; return the paths whose content changed.

    With ``check=True`` nothing is written (the list is what *would* change).
    """
    changed: List[str] = []
    for board, text in render_all(repo_root).items():
        path = index_path(repo_root, board)
        old: Optional[str] = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as fh:
                old = fh.read()
        if old != text:
            changed.append(path)
            if not check:
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write(text)
    return changed
