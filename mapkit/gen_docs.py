"""``docs/project-map.md`` and ``docs/glossary.md`` generator.

Committed output, byte-deterministic (no clock): ``python -m mapkit gen``
writes both in the same run as the INDEX files and the CLAUDE.md term block,
and ``tests/sim/test_mapkit_docs.py`` fails when a committed page is stale.
Writes nothing and returns ``[]`` when ``<repo>/map/`` does not exist.

Every link out of ``docs/`` is an absolute GitHub URL (``DOCUMENTATION_GUIDE.md``
section 2.3, pinned by ``tests/sim/test_docs_links.py``).
"""
from __future__ import annotations

import os
from typing import List, Optional

from mapkit import derive, ids
from mapkit.gen_glossary import load_glossary
from mapkit.items import INBOX_KINDS, Item, load_items
from mapkit.plans import Plan, load_plans
from mapkit.sitting import render_runbook

REPO_URL = "https://github.com/Project-DeepBlue-Juggling/Jugglebot/blob/main/"
DASH = "—"
_GEN = "`python -m mapkit gen`"


def _cell(value) -> str:
    text = " ".join(str(value).split()) if value not in (None, "") else ""
    return text.replace("|", "\\|") if text else DASH


def _plan_link(plan: Plan, text: Optional[str] = None) -> str:
    return "[%s](%splans/%s/%s)" % (text or plan.filename, REPO_URL, plan.board,
                                    plan.filename)


def _item_link(item: Item, text: Optional[str] = None) -> str:
    return "[%s](%smap/%s)" % (text or item.title, REPO_URL, item.filename)


def _tag(item: Item) -> str:
    """``JB-12 `` (with the trailing space) or nothing for an ID-less Item."""
    return (item.short_id + " ") if item.short_id else ""


def _stop_text(stop, plans_by_name) -> str:
    if stop.kind == "blocker":
        return "waiting on %s" % stop.label
    plan = plans_by_name.get(stop.plan)
    label = ("%s %s" % (stop.step_id, stop.label)) if stop.step_id else stop.label
    return "%s (%s)" % (label, _plan_link(plan, stop.plan)) if plan else label


def _owners(pathway: Item, plans: List[Plan], items: List[Item]) -> str:
    # names are de-duplicated case-insensitively below (plan owner: Harrison vs item owners: harrison)
    names: List[str] = []
    for src in (pathway.meta.get("owners") or []):
        names.append(str(src))
    for p in derive.pathway_plans(pathway, plans):
        if p.board in ("active", "parked") and p.meta.get("owner"):
            names.append(str(p.meta["owner"]))
    for t in derive.open_tickets(pathway, items):
        names.extend(str(o) for o in (t.meta.get("owners") or []))
    seen: List[str] = []
    for n in names:
        if n.lower() not in [x.lower() for x in seen]:
            seen.append(n)
    return ", ".join(seen) if seen else DASH


def render_project_map(repo_root: str) -> str:
    items = load_items(os.path.join(repo_root, "map"))
    plans = load_plans(repo_root)
    by_name = {p.filename: p for p in plans}
    order = derive.pathway_order(items)
    out: List[str] = [
        "# Project map", "",
        "Where each pathway of the Jugglebot project stands: its destination, how many stops "
        "are done, what comes next and what remains, who owns it, and what has been filed "
        "against it. Generated by %s from plan frontmatter and `map/` items; do not edit by "
        "hand. The page is as fresh as the last committed run." % _GEN, ""]
    dups = ids.duplicates(items)
    if dups:  # the gate (test_item_ids_unique) fails too; the page says so where it is read
        out += ["> **Warning: duplicate Item IDs** — %s. Run `python -m mapkit ids --repair`." % "; ".join(
            "%s: %s" % (k, ", ".join(ids.stem(i) for i in v)) for k, v in sorted(dups.items())), ""]
    for pw in order:
        out += ["## %s" % pw.title, "", "**Destination:** %s" % " ".join(
            str(pw.meta["destination"]).split()), ""]
        if pw.status != "active":
            out += ["_Status: closed (%s)._" % pw.status, ""]
            continue
        done, total = derive.progress(pw, plans)
        nxt = derive.next_stop(pw, plans, items)
        out += ["**Progress:** %d of %d stops done" % (done, total), "",
                "**Next:** %s" % (_stop_text(nxt, by_name) if nxt else DASH), "",
                "**Owners:** %s" % _owners(pw, plans, items), ""]
        remaining = [u for u in derive.units(pw, plans)
                     if u.status not in ("complete", "retired")]
        out.append("**Remaining:**")
        out.append("")
        if remaining:
            for u in remaining:
                out.append("- %s%s" % (_stop_text(u, by_name),
                                       " — in progress" if u.status == "in_progress" else ""))
        else:
            out.append("- %s" % DASH)
        out.append("")
        att = derive.attached(pw, items)
        out.append("**Attached inbox items:**")
        out.append("")
        if att:
            for i in att:
                out.append("- %s: %s%s (%s)" % (i.kind, _tag(i), _item_link(i), i.status))
        else:
            out.append("- %s" % DASH)
        out.append("")
    # Now / Next / Later grid
    out += ["## Now / Next / Later", "",
            "| Pathway | Now | Next | Later | Done |", "| --- | --- | --- | --- | --- |"]
    for pw in order:
        if pw.status != "active":
            out.append("| %s | %s | %s | %s | %s |" % (_cell(pw.title), DASH, DASH, DASH, "closed"))
            continue
        ln = derive.lanes(pw, plans, items)

        def names(lane) -> str:
            parts = []
            for e in lane:
                if isinstance(e, Item):
                    parts.append("%s %s" % (e.kind, e.title))
                elif e.kind == "blocker":
                    parts.append("waiting on %s" % e.label)
                else:
                    parts.append(("%s %s" % (e.step_id, e.label)) if e.step_id else e.label)
            return "; ".join(parts)
        out.append("| %s | %s | %s | %s | %s |" % (
            _cell(pw.title), _cell(names(ln["now"])), _cell(names(ln["next"])),
            _cell(names(ln["later"])), _cell(names(ln["done"]))))
    out.append("")
    # Inbox
    out += ["## Inbox", "",
            "Metrics: Effort xs/s/m/l/xl; HW none/bench-leg/robot; Owner none/decision/hands; "
            "Blast radius local/subsystem/cross-cutting/normative; Area = primary area "
            "(`DOCUMENTATION_GUIDE.md` 2.10); a dash is unrated.", "",
            "| ID | Kind | Title | Status | Priority | Effort | HW | Owner | Blast radius | Area "
            "| Pathway | Age |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    inbox = sorted((i for i in items if i.kind in INBOX_KINDS
                    and i.status in derive.OPEN_INBOX_STATUSES),
                   key=lambda i: (str(i.meta.get("created")), i.slug))
    titles = {p.slug: p.title for p in items if p.kind == "pathway"}
    for i in inbox:
        pw = i.meta.get("parent")
        out.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | filed %s |" % (
            _cell(i.short_id), i.kind, _cell(_item_link(i)), i.status, _cell(i.meta.get("priority")),
            *[_cell(i.meta.get(f)) for f in ("effort", "hardware", "owner", "radius", "area")],
            _cell(titles.get(pw, pw)), i.meta.get("created")))
    if not inbox:
        out.append("| " + " | ".join((DASH,) * 12) + " |")
    out.append("")
    # Open tickets
    blocks: List[str] = []
    for pw in order:
        tk = derive.open_tickets(pw, items)
        if not tk:
            continue
        blocks += ["### %s" % pw.title, ""]
        for t in tk:
            owners = ", ".join(str(o) for o in (t.meta.get("owners") or [])) or "unclaimed"
            rank = t.meta.get("rank")
            blocks.append("- %s%s — %s, %s, rank %s" % (
                _tag(t), _item_link(t), t.meta.get("type"), owners, rank if rank is not None else DASH))
        blocks.append("")
    if blocks:
        out += ["## Open tickets", ""] + blocks
    return "\n".join(out).rstrip("\n") + "\n"


def render_glossary_page(repo_root: str) -> str:
    entries = load_glossary(repo_root)
    out: List[str] = [
        "# Glossary", "",
        "The project's domain terms, grouped by cluster. Generated by %s from `GLOSSARY.md`; "
        "do not edit by hand. Use the term, never a word on its Avoid line." % _GEN, ""]
    cluster = None
    for e in entries:
        if e.cluster != cluster:
            cluster = e.cluster
            out += ["### %s" % cluster, ""]
        out += ["**%s**" % e.term, "", e.definition, ""]
        if e.avoid:
            out += ["_Avoid: %s_" % ", ".join(e.avoid), ""]
    return "\n".join(out).rstrip("\n") + "\n"


def write_docs(repo_root: str, check: bool = False, only: Optional[tuple] = None) -> List[str]:
    """Rewrite stale pages; return the paths that changed (or would, with ``check``)."""
    if not os.path.isdir(os.path.join(repo_root, "map")):
        return []
    changed: List[str] = []
    for rel, text in (("project-map.md", render_project_map(repo_root)),
                      ("glossary.md", render_glossary_page(repo_root)),
                      ("runbook.md", render_runbook(repo_root))):
        if only is not None and rel not in only:
            continue
        path = os.path.join(repo_root, "docs", rel)
        old = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as fh:
                old = fh.read()
        if old != text:
            changed.append(path)
            if not check:
                with open(path, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(text)
    return changed
